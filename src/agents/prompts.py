# 三、政策问答（RAG）
# ==============================================================================
#: 政策问答智能体（``AgentName.POLICY_RAG``）的基础提示词。
#:
#: ⚠️ 这个智能体的**全部价值**在于「答案有出处」。没有出处的政策回答
#: 和模型自己编的没有区别 —— 而差旅标准直接关系到用户能不能报销，
