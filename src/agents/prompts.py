def prompt_for(agent_name: str) -> str:
    """取某个智能体的基础提示词。

    ⚠️ 认不出的名字返回**一个明确的兜底提示词**，而不是空串或 ``None``。
    空提示词会让智能体以「没有身份设定」的状态运行，行为无法预测；
    而一段说明「你是一个差旅助手，但配置可能有误」的提示词，
    至少能让它表现得像个正常的助手 —— 用户不会察觉到异常。

    ⚠️ 兜底提示词里**不含**任何「配置有误」这类给开发者看的话：它同样会进
    模型上下文。开发者要看的是日志（本函数会记一条 warning）。

    Args:
        agent_name (`str`): 智能体名。

    Returns:
        `str`: 对应的基础提示词；未登记时返回兜底提示词。
    """
    known = PROMPTS.get(agent_name)
    if known is not None:
        return known

    import logging

    logging.getLogger(__name__).warning(
        "智能体 %r 没有登记提示词，已回退到兜底提示词。请检查 src/agents/prompts.py 的 PROMPTS。",
        agent_name,
    )
    return _FALLBACK_PROMPT


#: 未登记智能体的兜底提示词。
#:
#: ⚠️ 刻意写成「通用差旅助手」而不是「未知智能体」。后者会让模型意识到
#: 自己处于异常状态，进而在回复里表现出来（「我似乎没有正确的配置」），
#: 而用户看到这句话只会困惑。提示词是给模型看的，不是给开发者看的。
_FALLBACK_PROMPT = """\
你是 AliGo 差旅助手，帮企业员工处理出差相关的事务：规划行程、查询交通住宿、
核对差旅标准、办理申请、查询订单。

价格、班次、酒店、差旅标准这类事实都要通过工具查询，不要凭记忆回答。
信息不足时先问清楚最关键的要素，再往下推进。

用中文回答，简洁、结论先行、像同事之间沟通。
"""

