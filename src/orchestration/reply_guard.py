def _user_text_from_inputs(inputs: Any) -> str:
    """从 ``on_reply`` 收到的 ``inputs`` 里抽出**用户本轮说过的原话**。

    Args:
        inputs (`Any`): 框架原样传进来的 ``inputs``。类型是
            ``Msg | list[Msg] | UserConfirmResultEvent | UserInterruptEvent
            | ExternalExecutionResultEvent | None``（见
            ``agentscope/agent/_agent.py:900-909`` 的 ``_reply`` 签名）。

    Returns:
        `str`: 拼接后的用户文本；取不到时返回空串。

    ⚠️ 这个函数**只有一个用途**：让 :func:`_ungrounded_limit_claims` 知道
    哪些数字是用户自己报的（「我订了 500 的能报吗」里的 500 不是编造）。
    因此它**刻意不去解析** HITL 确认 / 打断 / 外部执行结果这三类事件 ——
    它们不是 ``Msg`` 的子类，isinstance 自然落空返回空串。空串只会让闸门
    **更保守**（多拦一次），不会让它误伤；为了「少冤枉一次」去多解析三种
    事件结构，是在给闸门加新的出错点，不划算。

    ⚠️ 已知局限：本函数只覆盖**本轮**输入。用户在前几轮报过、本轮没再报的
    数字不在这里 —— 那条路走的是「动态 Prompt 注入过的数字」豁免
    （``_ungrounded_limit_claims`` 的合法来源 4），它登记的是**我们写进
    system prompt 的那部分用户数据**（预算、天数、人数、画像里的数字）。

    ⚠️ 两者覆盖面的差：来源 4 覆盖的是「要素收集链路把用户的话转成了
    结构化字段」的那些数字（用户说「预算 15000」→ 字段 → prompt）。
    用户随口提过、但没进任何字段、也没进本轮输入的数字（例如上一轮说
    「我上次订的是 480」而本轮问差标），仍然**不在**任何豁免里 ——
    保留这个缺口是有意的：要补它就得把整段对话历史当成合法来源，
    而那等于把闸门的事实基准从「本轮工具返回」放宽到「用户说过的任何话」，
    放走的编造会明显变多（模型完全可以从历史里挑一个数来冒充差标）。

    ⚠️ 非文本块（图片、文件）不参与：里面没有可以被引用的数字。
    """
    if isinstance(inputs, Msg):
        return inputs.get_text_content() or ""
    if isinstance(inputs, (list, tuple)):
        parts = [m.get_text_content() or "" for m in inputs if isinstance(m, Msg)]
        return "\n".join(p for p in parts if p)
    return ""


@dataclass
class _ReplyState:
    """一次回复的可变状态。

    ⚠️ 实例活在 :meth:`ReplyGuardMiddleware.on_reply` 的局部变量里，**不是**
    中间件的属性 —— 中间件实例被同一个 agent 的所有回复共用，把状态挂上去
    会让并发回复互相冲掉（见模块文档最后一段）。

    Attributes:
        reply_id (`str`): 当前回复的 id，用于合成事件的 ``reply_id``。
        round_events (`list[EventBase]`): 本轮缓冲的文本事件（原样保留，
            剥离后没变化时按原事件发出，保住 block id）。
        round_text (`list[str]`): 本轮文本的增量片段。
        round_tools (`list[str]`): 本轮出现过的工具名。
        emitted (`bool`): 是否已经向用户发出过正文。
        emitted_text (`str`): **实际发给用户**的正文（供收尾审计用）。
        drafts (`list[str]`): 被丢弃的草稿（仅用于日志、丢弃计数与兜底）。
        retries (`int`): 已重试次数。
        pending_problem (`str | None`): 本轮候选答复被拒的原因。
        tool_text (`list[str]`): 工具返回文本片段（用于数值上报）。
        tool_text_chars (`int`): 已累计的工具文本长度（用于封顶）。
        policy_tools (`list[str]`): 本次回复调用过的**差标工具**名。
            非空才启用事实接地闸门（见 :func:`_ungrounded_limit_claims`）。
        user_text (`str`): 用户**本次回复**说过的话（多轮输入拼接）。
            传给 :func:`_ungrounded_limit_claims` 做「用户自己报过的数」豁免。
            取不到时保持空串 —— 闸门只会更保守，不会更激进。
        blocked_texts (`set[str]`): 被事实接地闸门拦下的正文（键为
            ``strip()`` 后的文本，见 :meth:`ReplyGuardMiddleware._settle_round`）。
            只被 :meth:`ReplyGuardMiddleware._fallback_if_silent` 读取 ——
            用来阻止「拦下的编造被兜底原样复活」（2026-10-04 缺陷 F4）。
        block_seq (`int`): 已合成的 block 数（用来生成唯一 block id）。
    """

    reply_id: str = ""
    round_events: list[EventBase] = field(default_factory=list)
    round_text: list[str] = field(default_factory=list)
    round_tools: list[str] = field(default_factory=list)
    emitted: bool = False
    emitted_text: str = ""
    drafts: list[str] = field(default_factory=list)
    retries: int = 0
    pending_problem: str | None = None
    tool_text: list[str] = field(default_factory=list)
    tool_text_chars: int = 0
    policy_tools: list[str] = field(default_factory=list)
    ungrounded_limits: list[str] = field(default_factory=list)
    user_text: str = ""
    blocked_texts: set[str] = field(default_factory=set)
    block_seq: int = 0

    def begin_round(self) -> None:
        """开始新的一轮模型调用：清空本轮缓冲。"""
        self.round_events = []
        self.round_text = []
        self.round_tools = []

    def round_content(self) -> str:
        """返回本轮已缓冲的文本。"""
        return "".join(self.round_text)


# ==============================================================================
# 四、事件合成
# ==============================================================================
def _synth_text_events(reply_id: str, text: str, block_id: str) -> list[EventBase]:
    """把一段纯文本合成为一对 ``TEXT_BLOCK_START/DELTA/END`` 事件。

    Args:
        reply_id (`str`): 回复 id（必须与消息 id 一致，否则服务端会跳过）。
        text (`str`): 要发出的正文。
        block_id (`str`): 块的 id（由调用方保证同一回复内不重复）。

    Returns:
        `list[EventBase]`: 三个事件，顺序为 START → DELTA → END。

    ⚠️ 必须是 START → DELTA → END 三步：服务端的
    ``Msg.append_event`` 靠 ``TEXT_BLOCK_START`` **创建**块，
    而后面的 DELTA/END 都是 ``_find_block`` 去找已存在的块，
    找不到只记一条 warning 就丢掉（``message/_base.py``）。
    """
    return [
        TextBlockStartEvent(reply_id=reply_id, block_id=block_id),
        TextBlockDeltaEvent(reply_id=reply_id, block_id=block_id, delta=text),
        TextBlockEndEvent(reply_id=reply_id, block_id=block_id, text=text),
    ]


