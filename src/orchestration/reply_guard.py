#: 现在的写法只认「计划性动词 + 第一人称」：「I need to check…」是独白，
#: 「I checked…」是答复；``^I'll`` / ``^I will`` 保留是因为缩写形式几乎只
#: 出现在打算里（实测的 A 类缺陷正是「I'll wait for the policy agent's report.」）。
#:
#: ⚠️ 2026-10-04 删掉了五条**结论形状**的判据（对抗验证逐条复现，见
#: ``tests/test_orchestration_reply_guard.py`` 的 ``_REAL_ANSWERS``）：
#:
#:     ``^按照(工作方式|我的|上述)``  ``^根据(我的|工作方式|上)``
#:     ``^这(是|涉及|属于)(一个)?(差旅|政策|标准)``  ``^我需要``
#:     ``^现在(我|看|标)``  →  收窄成 ``^现在我看``
#:
