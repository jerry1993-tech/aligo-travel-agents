#:
#: ⚠️ 英文那几条**必须是具体动词**，不能写成 ``^I\b`` / ``^Since\b``：
#: 那会把「I recommend the Beijing hotel at 600 CNY per night.」
#: 「Since your trip starts Monday, book before Friday.」这类**正经英文答复**
#: 判成独白 —— 单段回复会被 ``_answer_problem`` 整段拒绝，用户拿到的是一句
#: 道歉话术而不是答案。这是**对抗性评审实测出来的**（四条英文真答案全被判
