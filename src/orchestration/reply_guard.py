    "稍等",
    "稍候",
    "请等",
    "等待",
    # —— 进行时：「正在做某事」但结果还没回来 -----------------------------
    "正在检索",
    "正在查询",
    "正在为您",
    "正在处理",
    "正在查看",
    "检索中",
    "查询中",
    "处理中",
    # —— 安抚：「马上就好」式的收尾 ---------------------------------------
    "马上回来",
    "马上就好",
    "马上给您",
    "这就为您",
    "即刻为您",
    # —— 英文形态（模型偶尔整句英文）--------------------------------------
    # ⚠️ 只收「整句就是等待」的短语，不收 ``check`` 这类裸动词 ——
