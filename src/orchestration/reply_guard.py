# 五、中间件
# ==============================================================================
class ReplyGuardMiddleware(MiddlewareBase):
    """回复守卫（见模块文档字符串）。

    Attributes:
        _enabled (`bool`): 总开关。关闭后本中间件**完全透明**
            （事件原样透传，连缓冲都不做），用于排障与 A/B 对比。
        _max_retries (`int`): 单次回复内最多重试几轮。
    """

    def __init__(self, *, enabled: bool = True, max_retries: int = 2) -> None:
        """初始化。

        Args:
            enabled (`bool`): 是否启用。默认启用。
            max_retries (`int`): 重试上限（``0`` 表示不重试，只剥离 + 兜底）。
                ⚠️ 上限的存在理由见模块文档「重试机制」第 3 条。
        """
        self._enabled = enabled
        self._max_retries = max(0, int(max_retries))

    # --------------------------------------------------------------------------
    # 钩子
    # --------------------------------------------------------------------------
    async def on_reply(
        self,
        agent: Any,
        input_kwargs: dict,
        next_handler: Callable[..., AsyncGenerator],
    ) -> AsyncGenerator:
        """拦截整轮回复，按轮剥离草稿并在必要时要求重说。

        Args:
            agent (`Any`): 框架传入的 agent 实例（本中间件用它查工具是否只读）。
            input_kwargs (`dict`): 触发本次回复的输入。
            next_handler (`Callable[..., AsyncGenerator]`): 下一层处理函数。

        Yields:
            `EventBase`: 过滤后的事件流。

        ⚠️ 所有状态都在 ``state`` 这个**局部变量**里（见模块文档最后一段）。
        """
        if not self._enabled:
            # 关闭时一行都不多做：连事件类型都不判断，避免出现
            #「关了开关但行为仍有细微差别」这种最难查的状态。
            async for event in next_handler(**input_kwargs):
                yield event
            return

        state = _ReplyState()
        # ⚠️ 用户原话在**整轮回复内不变**，所以在这里取一次就够了，
        # 不放进下面 ``ReplyStartEvent`` 的重置分支 —— 重试（吞掉
        # ``ReplyEndEvent`` 再走一轮）时用户输入并没有变，放进去只会
        # 多一个「重置后忘了重新赋值」的出错面。
        state.user_text = _user_text_from_inputs(input_kwargs.get("inputs"))

        # ⚠️ ``try/finally`` 不是为了吞异常（异常照样向上抛，取消与错误传播
        # 不能破坏），而是为了让收尾上报在任何退出路径上都执行 —— 理由见
        # ``finally`` 里的注释。
        try:
            async for event in next_handler(**input_kwargs):
                # ⚠️ 补记 reply_id：**HITL 续答不发 ``ReplyStartEvent``**
                # （``agentscope/agent/_agent.py:1105-1118`` 只在「新回复」分支发它；用户确认
                # 订单后的续答走 ``_handle_incoming_event``，只发工具结果事件）。
                # 不补记的话 ``state.reply_id`` 会一直是空串，之后所有合成事件
                # 都会被 ``Msg.append_event`` 以「id 不匹配」静默丢弃 —— 而实时
                # SSE 照样发布，于是「用户当场看得到、刷新后消失」。
                # 实测依据见 :meth:`_resolve_reply_id` 的文档。
                if not state.reply_id:
                    incoming_id = getattr(event, "reply_id", "")
                    if incoming_id:
                        state.reply_id = incoming_id

                if isinstance(event, ReplyStartEvent):
                    state.reply_id = event.reply_id
                    state.emitted = False
                    state.emitted_text = ""
                    state.drafts = []
                    state.retries = 0
                    state.pending_problem = None
                    state.tool_text = []
                    state.tool_text_chars = 0
                    state.policy_tools = []
                    state.ungrounded_limits = []
                    state.blocked_texts = set()
                    state.block_seq = 0
                    state.begin_round()
                    yield event
                    continue

                if isinstance(event, ModelCallStartEvent):
                    state.begin_round()
                    yield event
                    continue

                if isinstance(
                    event,
                    (TextBlockStartEvent, TextBlockDeltaEvent, TextBlockEndEvent),
                ):
                    # 只缓冲，先不发 —— 见模块文档「为什么整轮缓冲」。
                    state.round_events.append(event)
                    if isinstance(event, TextBlockDeltaEvent):
                        state.round_text.append(event.delta)
                    continue

                if isinstance(event, ToolCallStartEvent):
                    # 工具调用必须照常透传：它是用户可见的执行过程（思考链），
                    # 也是服务端记录本条回复「做过什么」的依据。
                    state.round_tools.append(event.tool_call_name)
                    if event.tool_call_name in _POLICY_LIMIT_TOOLS:
                        # 记「调过」而不是「调成功」：工具失败时给出的
                        # 编造数字同样要拦（失败时正文本就该说查不到）。
                        state.policy_tools.append(event.tool_call_name)
                    yield event
                    continue

                if isinstance(event, ToolResultTextDeltaEvent):
                    if state.tool_text_chars < _MAX_TOOL_TEXT_CHARS:
                        state.tool_text.append(event.delta)
                        state.tool_text_chars += len(event.delta)
                    yield event
                    continue

                if isinstance(event, ModelCallEndEvent):
                    for settled in await self._settle_round(agent, state):
                        yield settled
                    state.begin_round()
                    yield event
                    continue

                if isinstance(event, ReplyEndEvent):
                    if self._should_retry(agent, state, event):
                        # ⚠️ 刻意**不** yield 这个事件 —— 这就是「吞掉」，
                        # 框架因此会再跑一轮（见模块文档「重试机制」）。
                        self._request_retry(agent, state)
                        continue
                    # ⚠️ 兜底**只在正常结束**时补。中断（用户按了停止）时补一段
                    # 「后台没返回有效内容，麻烦你再问我一次」是**错误归因** ——
                    # 用户自己取消的，不是后台坏了；而超迭代/出错的收尾由框架与
                    # ``src/chains/events.py`` 负责（那里会把任务标记为失败），
                    # 我们再插一段话只会和它抢屏幕，还会落进历史消息。
                    if event.finished_reason == ReplyFinishedReason.COMPLETED:
                        for synthesized in self._fallback_if_silent(agent, state):
                            yield synthesized
                    yield event
                    continue

                yield event
        finally:
            # ⚠️ 放在 ``finally`` 里：模型侧抛异常时 ``async for`` 直接向上
            # 穿透，收尾上报不能因此被跳过 —— 恰恰是异常那一次最需要留下
            # 「上一轮发了什么、有没有无依据金额」的记录。
            # ⚠️ 异常时**不**补发本轮缓冲的文本：缓冲里可能是一段没写完的话，
            # 发出去比不发更糟。此时由服务层的失败话术兜底（已核实的框架行为：
            # 普通异常不发 ``ReplyEndEvent``，``agentscope/agent/_agent.py:1271-1304`` 只捕获
            # ``CancelledError``），这是**有意**的取舍，不是遗漏。
            self._report(state)

    # --------------------------------------------------------------------------
    # 本轮结算
    # --------------------------------------------------------------------------
    async def _settle_round(
        self,
        agent: Any,
        state: _ReplyState,
    ) -> list[EventBase]:
        """结算一轮模型调用的文本缓冲，返回**要发出**的事件。

        Args:
            agent (`Any`): agent 实例。
            state (`_ReplyState`): 回复状态（本方法会就地修改）。

        Returns:
            `list[EventBase]`: 要透传给服务端的文本事件；空列表表示全丢。

        三种结局：

            1. **工具轮**（本轮有工具调用）→ 文字是草稿，丢弃。
               例外：本轮有「需要用户确认」的工具（非只读）时，文字**不按
               草稿处理** —— 那是提示词要求的复述（申请事由、金额、日期）。
               ⚠️ 但「不按草稿处理」**不等于「跳过检查」**：例外轮与正文轮
               走**同一条**剥离 + 闸门流水线，见下面 ⚠️。
            2. **正文轮**且剥离后可用 → 发出（原文没变就复用原事件）。
            3. **正文轮**但剥离后不可用 → 丢弃，并记下原因供重试使用。

        ⚠️ 例外轮早先是**整轮原样放行**的：一进 ``_round_needs_recitation``
        分支就 ``return list(state.round_events)``，把 ``_strip_drafts``、
        ``_answer_problem``、``_ungrounded_limit_offenders`` 全跳过了。
        2026-10-04 现场复现：同一轮里 ``check_travel_policy``（只读）与
        ``submit_approval``（写）一起被调用，工具返回 ``600``、正文却写
        「我先调用 check_travel_policy 核对，酒店差标是 500 元/晚。」
        —— 编造的 500 与内部工具名**一起**发给了用户。原因就是把「这一轮
        的文字可能是给用户看的复述」误当成了「这一轮的文字一定是对的」。

        ⚠️ 拒绝例外轮的正文**不会**影响人工确认：确认框上的事由与金额来自
        ``submit_approval`` 的**调用参数**（工具调用块），不是这段文字。
        所以这里的取舍是「宁可让用户看不到复述，也不让编造的数值上屏」，
        与 :data:`_PLACEHOLDER_MAX_RESIDUE` 那条「宁可放过空话，也不改坏
        真答案」的方向相反 —— 因为编造数值是**误导决策**，比少一段复述重。
        """
        text = state.round_content()
        if not text.strip() and not state.round_events:
            return []

        # 本轮的文字是不是「给用户看的确认复述」？
        # ⚠️ 判据全在 _round_needs_recitation（含框架内部机制工具的排除），
        # 这里不做第二套判断 —— 两套判据会一边剥一边留。
        recitation = False
        if state.round_tools:
            recitation = await self._round_needs_recitation(
                agent,
                state.round_tools,
            )

        if state.round_tools and not recitation:
            if text.strip():
                state.drafts.append(text.strip())
                # ⚠️ 2026-10-04 按**形状**分两类上报（M1）。原先是单一动作
                # ``dropped_tool_round``，而那一条曲线回答不了「提示词该改哪、
                # 改得有没有效」：
                #
                #     ``..._narration``  这段文字**本模块的判据认得**（草稿 /
                #         占位话术）—— 就是提示词里「工具轮别配文字」要治的
                #         那一类。它下降 = 提示词在起作用。
                #     ``..._other``      判据认不出来。**这一类要盯住**：工具轮的
                #         文字是**静默丢弃**的，若里面其实有给用户的答案，
                #         用户就少了一段内容，而且没有任何重说。
                #
                # 判据复用 :func:`_is_draft` 与 :func:`_is_placeholder`
                # （同模块、无新口径）。注意文本里若**混着**草稿与真内容，
                # 段首命中判据即算 narration —— 这正是想要的粒度：
                # 「模型还在工具轮里写过程叙述」这个事实成立就够了。
                observable = _is_draft(text) or _is_placeholder(text)
                observe_reply_guard(
                    "dropped_tool_round_narration"
                    if observable
                    else "dropped_tool_round_other",
                )
                if not observable:
                    # ⚠️ 只给**判据认不出**的这一类留样。理由：这类文本在本条
                    # 路径外**零留痕** —— 事件被静默丢弃、``drafts`` 随请求
                    # 结束蒸发、指标只有计数（没有内容）。少了这一行，「被吃掉
                    # 的到底是什么」就完全无从查起，而「它是不是一段真答案」
                    # 恰恰是决定要不要改判据的唯一依据。
                    #
                    # narration 那类**刻意不留样**：它每次都要出现（就是提示词
                    # 要治的东西），留样只会把日志淹掉，而它的形状本来就由
                    # ``_is_draft`` 的定义写死了。
                    #
                    # 级别取 DEBUG、长度截到 200：正文属于用户可见内容，
                    # 默认级别（INFO 起）不该出现；截断手法与
                    # ``src/chains/events.py`` 里对解析失败载荷的 ``%.200s``
                    # 是同一个先例（「打原文，但打不多」）。
                    stripped = text.strip()
                    logger.debug(
                        "回复守卫丢弃了一段判据认不出的工具轮文字（长度 %d）：%.200s",
                        len(stripped),
                        stripped,
                    )
            return []

        # ⚠️ 例外轮**落到这里**继续走流水线（而不是提前 return）—— 这正是
        # 上面那条复现缺陷的修复。剥离与两个闸门对例外轮一视同仁。
        cleaned, removed = _strip_drafts(text)
        problem = _answer_problem(cleaned)
        if problem is None:
            # ── 事实接地闸门（判据与先决条件都在 _ungrounded_limit_offenders）──
            # 2026-10-03 实测：工具每轮都返回同一个数，正文却有 3/8 轮写成
            # 另一个数 —— 那是模型的先验，不是工具的事实。
            offenders = self._ungrounded_limit_offenders(agent, state, cleaned)
            if offenders:
                problem = "ungrounded_limit"
                state.ungrounded_limits = offenders
                # ⚠️ 记下这段文本本身（不只是数值），供兜底阶段拒绝复活它
                # （2026-10-04 缺陷 F4）。键取 ``strip()`` 后的文本：
                # 兜底阶段拿 ``state.drafts`` 里的 ``text.strip()`` 重新剥离，
                # 两处的结果只可能差在首尾空白上。详见 _fallback_if_silent。
                state.blocked_texts.add(cleaned.strip())
                logger.warning(
                    "回复守卫拦下一段可能编造差标的正文（agent=%s，数值=%s）。",
                    getattr(agent, "name", "?"),
                    offenders[:5],
                )
        if problem is not None:
            state.pending_problem = problem
            if text.strip():
                state.drafts.append(text.strip())
            observe_reply_guard(f"rejected_{problem}")
            logger.warning(
                "回复守卫拦下一段不可用正文（agent=%s，原因=%s，长度=%d）。",
                getattr(agent, "name", "?"),
                problem,
                len(text),
            )
            return []

        if recitation:
            # ⚠️ 指标记在**活下来之后**：``kept_confirmation_round`` 的含义是
            # 「确认复述按用户可见的文字保留」。放在函数开头记的话，
            # 被闸门拦下的那一段也会记成「保留」，指标就与事实相反了。
            observe_reply_guard("kept_confirmation_round")
        state.emitted = True
        state.pending_problem = None
        state.ungrounded_limits = []
        state.emitted_text += cleaned
        # ⚠️ 判据是「**剥完的文本与原文相等**」，不是「``removed == 0``」。
        # 两者今天等价（``_strip_drafts`` 的契约：``removed == 0`` 必返回
        # 原文、``removed > 0`` 必返回拼接结果），但契约是靠注释维持的，
        # 而这里的分支决定**能不能复用原事件**：一旦将来有哪条清洗路径
        # 动了文本却忘了自增 ``removed``，拿旧计数当判据就会把改过的文本
        # 配着原文的事件发出去（用户看到的还是旧文本 —— 而且是静默的）。
        # 拿文本本身比，这个错误就没有发生的余地。
        if cleaned == text:
            observe_reply_guard("clean")
            return list(state.round_events)

        observe_reply_guard("stripped")
        logger.info(
            "回复守卫剥掉 %d 段草稿（agent=%s，剩余 %d 字）。",
            removed,
            getattr(agent, "name", "?"),
            len(cleaned),
        )
        # ⚠️ 剥过之后**不能**复用原事件（那会把草稿一起发出去），
        # 所以合成一对新事件。block id 由计数器派生：若同一回复里有两轮
        # 都被剥离，用 ``reply_id`` 派生的固定 id 会**撞块** —— 第二个
        # ``TEXT_BLOCK_START`` 建不出新块时，后续 DELTA 会被 ``_find_block``
        # 归到第一个块上（``message/_base.py``）。
        return _synth_text_events(
            self._resolve_reply_id(agent, state),
            cleaned,
            self._next_block_id(state, "guard"),
        )

    # --------------------------------------------------------------------------
    # id 解析
    # --------------------------------------------------------------------------
    @staticmethod
    def _resolve_reply_id(agent: Any, state: _ReplyState) -> str:
        """取当前回复 id，供合成事件使用。

        Args:
            agent (`Any`): agent 实例。
            state (`_ReplyState`): 回复状态。

        Returns:
            `str`: 回复 id；两处都取不到时返回空串。

        ⚠️ 这里必须**两级兜底**，因为 HITL 续答（用户确认订单后继续回复）
        不发 ``ReplyStartEvent``：

            1. ``state.reply_id`` —— 正常回复由 ``REPLY_START`` 赋值，
               续答由 ``on_reply`` 循环里的补记赋值（任何带 id 的事件）；
            2. ``agent.state.reply_id`` —— 续答时 ``reply_context`` 是**沿用**
               的（``agentscope/agent/_agent.py:1109-1114`` 只在新回复分支重建它），所以那里
               存着原来那条回复的 id。

        取不到时返回空串，让事件照发 —— 此时服务端的 ``append_event`` 会跳过
        它们，与「不发」等价，但至少实时流的行为不变。
        """
        if state.reply_id:
            return state.reply_id
        return getattr(getattr(agent, "state", None), "reply_id", "") or ""

    @staticmethod
    def _next_block_id(state: _ReplyState, prefix: str) -> str:
        """生成同一回复内唯一的 block id。

        Args:
            state (`_ReplyState`): 回复状态（就地自增计数器）。
            prefix (`str`): id 前缀（``guard`` / ``guard-fallback``）。

        Returns:
            `str`: 唯一 block id。
        """
        state.block_seq += 1
        return f"{prefix}-{state.block_seq}-{state.reply_id or 'noid'}"

    async def _round_needs_recitation(
        self,
        agent: Any,
        tool_names: list[str],
    ) -> bool:
        """本轮是否含「需要用户确认」的工具（即写操作）。

        Args:
            agent (`Any`): agent 实例。
            tool_names (`list[str]`): 本轮调用的工具名。

        Returns:
            `bool`: ``True`` 表示本轮的文字**可能是给用户看的复述**，不能剥。

        ⚠️ 判据是工具自身的 ``is_read_only``（见模块文档「判定规则」），
        **但先要排掉框架的内部机制工具**（:data:`INTERNAL_TOOLS`）——
        它们自报 ``is_read_only=False``，含义却是「会改内部状态」，
        而不是「这一轮的文字是给用户看的复述」：

        ==============================  ==============  ==========
        工具                             自报 read_only  本轮文字
        ==============================  ==============  ==========
        TeamCreate / AgentCreate / Say  True            剥（本来就对）
        TaskCreate / TaskList / TaskGet False           **剥**（踩过的坑）
        reset_tools                     False           **剥**（踩过的坑）
        ToolStop                        False           **剥**（踩过的坑）
        我们的 submit_approval 等写工具     False          保留（复述）
        Bash / Write / Edit 等工作区工具   False          保留（复述）
        ==============================  ==============  ==========

        ⚠️ 中间两行是 2026-10-03 用**真实** ``Toolkit`` 装配实测出来的
        （单组时 ``['dummy']``，加了 ``schedule_tools`` 组后
        ``['reset_tools', 'dummy', 'TaskList', ...]``）。早先这里只有
        ``is_read_only`` 一条判据，注释里还断言「框架的团队/元工具自报
        ``is_read_only=True``」—— 那句只对**团队**工具成立，于是模型
        「我先建个任务清单」这一类过程独白被原样发给了用户，
        而守卫存在的全部理由就是消灭这类文本。

        ⚠️ ``ToolStop`` 是同一个坑换了个工具名：它由
        ``BackgroundTaskManager.list_tools()`` **无条件**挂载，自报
        ``is_read_only=False``，实测 ``_round_needs_recitation(['ToolStop'])``
        返回 True —— 「我先把后台那个还在跑的任务停掉。」照样发给用户。

        ⚠️ 最后一行（工作区六件套）是**刻意保留**的：它们是货真价实的写
        工具，那一轮的文字很可能是「文件已生成」这类用户可见的交代。
        名单边界的判据是「这轮有没有用户可见的写操作」，不是「是不是框架
        挂上来的」—— 所以 ``WORKSPACE_TOOLS`` 只进快车道收窄表
        （:data:`src.orchestration.lane.LANE_HIDDEN_TOOLS`），不进这里。

        ⚠️ 顺序不能反：名单判断必须**先于** ``is_read_only`` 判断，
        且只对名单里的名字生效。一轮里同时调了 ``TaskList`` 与
        ``submit_approval`` 时，仍然是写工具说了算（保留复述）。

        查不到工具时**按只读处理**（即允许剥离），理由：查不到的多半是
        框架的团队/规划工具（本来就该剥），而真正的写操作工具是我们自己
        注册的、一定查得到。万一判断错了，用户的兜底是「确认框上仍写明了
        事由与金额」—— 而反过来（把工具轮的草稿全留下）是**必然**的缺陷。
        """
        for name in tool_names:
            # ⚠️ 名单里的名字**跳过**而不是直接 return False：同一轮里
            # 可能还有真正的写工具，判据要落在「有没有写工具」上。
            if name in INTERNAL_TOOLS:
                continue
            try:
                tool = await agent.toolkit.get_tool(name)
            except Exception:  # noqa: BLE001 —— 查工具失败不该让回复失败
                logger.warning("回复守卫查工具 %r 失败，按只读处理。", name)
                continue
            if tool is None:
                continue
            if not getattr(tool, "is_read_only", True):
                return True
        return False

    # --------------------------------------------------------------------------
    # 收尾：重试与兜底
    # --------------------------------------------------------------------------
    def _should_retry(
        self,
        agent: Any,
        state: _ReplyState,
        event: ReplyEndEvent,
    ) -> bool:
        """判断是否应该吞掉这次回复结束、要求模型重说。

        Args:
            agent (`Any`): agent 实例（用来读迭代余量）。
            state (`_ReplyState`): 回复状态。
            event (`ReplyEndEvent`): 结束事件。

        Returns:
            `bool`: ``True`` 表示吞掉并重试。

        四个条件**必须同时满足**：

            1. 还没有向用户发出过任何正文（``not state.emitted``）——
               已经答了就绝不再重说一遍，那会在界面上留下两段回答；
            2. 还有重试额度；
            3. 结束原因是 ``COMPLETED`` —— 中断/超迭代/出错的结束**不允许**吞
               （见模块文档「重试机制」第 1 条）；
            4. ReAct 迭代还余得下（见 :data:`_RETRY_MIN_ITER_BUDGET`）。

        ⚠️ 第 4 条是**对抗性评审挑出来的**：重试会消耗迭代，而 ``cur_iter``
        一旦超过上限，框架就把结束原因改成 ``EXCEED_MAX_ITERS``。那时
        「一次本来成功的回复」会变成「一次被判失败的回复」——
        为了修一句不好听的话而把整次请求搞失败，是纯粹的自伤。
        读不到迭代信息时按「余量充足」处理（返回 ``True`` 继续走前三条），
        因为读不到不等于没有余量，而少重试一次的代价只是一次体验不佳。
        """
        if state.emitted:
            return False
        if state.retries >= self._max_retries:
            return False
        if event.finished_reason != ReplyFinishedReason.COMPLETED:
            return False
        if self._structured_output_satisfied(agent):
            # ⚠️ 结构化输出已经满足时**不许吞**：框架在「schema 已满足」的
            # ``Exit`` 分支**不调用模型**就能再次发出 ``ReplyEndEvent``
            # （``agentscope/agent/_agent.py:3554-3578``），连吞两次且中间没有进展就会撞上
            # ``made_progress`` 守卫抛 ``RuntimeError``（``agentscope/agent/_agent.py:1165-1173``）。
            # 而且重说也改变不了结局 —— 结构化结果已经定了。
            # 当前装配下 ``main_plan`` 不带 ``structured_schema``，所以这条
            # 分支**不可达**；写在这里是为了将来给它加上结构化输出时不会
            # 变成一次线上崩溃（见 ``_structured_output_satisfied``）。
            observe_reply_guard("retry_skipped_structured")
            return False
        if self._iteration_budget_exhausted(agent):
            observe_reply_guard("retry_skipped_no_budget")
            logger.warning(
                "回复守卫放弃重试：ReAct 迭代余量不足（agent=%s）。",
                getattr(agent, "name", "?"),
            )
            return False
        return True

    @staticmethod
    def _structured_output_satisfied(agent: Any) -> bool:
        """判断该 agent 本轮的结构化输出是否已经满足。

        Args:
            agent (`Any`): agent 实例。

        Returns:
            `bool`: 既有 schema、又已经拿到结构化结果时返回 ``True``。

        ⚠️ 读的是 ``agent.state.reply_context`` 的三个字段
        （``state/_state.py`` 的 ``reply_context`` → ``reply_context.structured_schema``
        / ``structured_output``）。任何一处读不到都返回 ``False``
        （按「没这回事」处理）—— 与 :meth:`_iteration_budget_exhausted` 同理：
        判错的代价不对称，误判成「已满足」会白白放弃一次能救回的重试。
        """
        try:
            context = agent.state.reply_context
        except Exception:  # noqa: BLE001 —— 读不到就当没有结构化输出
            return False
        if context is None or not getattr(context, "structured_schema", None):
            return False
        return getattr(context, "structured_output", None) is not None

    @staticmethod
    def _iteration_budget_exhausted(agent: Any) -> bool:
        """判断该 agent 的 ReAct 迭代余量是否已不足以再重试一次。

        Args:
            agent (`Any`): agent 实例。

        Returns:
            `bool`: ``True`` 表示余量不足，不应重试。

        ⚠️ 取值路径是 ``agent.state.cur_iter`` 与 ``agent.react_config.max_iters``
        （``state/_state.py`` 的 ``cur_iter`` 属性 → ``reply_context.cur_iter``；
        ``agent/_config.py`` 的 ``ReactConfig.max_iters``）。任何一处取不到就
        返回 ``False``（按余量充足处理）—— 判错的代价不对称：误判「有余量」
        最多是多一次重试，误判「没余量」会让本来能救回的回复直接退回兜底。
        """
        try:
            remaining = int(agent.react_config.max_iters) - int(agent.state.cur_iter)
        except Exception:  # noqa: BLE001 —— 见 docstring 的不对称性说明
            return False
        return remaining < _RETRY_MIN_ITER_BUDGET

    def _request_retry(self, agent: Any, state: _ReplyState) -> None:
        """把纠正指令塞进上下文，并记账。

        Args:
            agent (`Any`): agent 实例。
            state (`_ReplyState`): 回复状态（就地修改 ``retries``）。

        ⚠️ 指令必须**由我们自己塞**：框架吞掉 ReplyEndEvent 之后走的是
        ``Reasoning(hint=None)`` 分支，不会替我们告诉模型刚才发生了什么
        （见模块文档「重试机制」第 2 条）。
        """
        state.retries += 1
        state.begin_round()
        observe_reply_guard(f"retry_{state.pending_problem or 'empty'}")
        logger.warning(
            "回复守卫要求重说（agent=%s，第 %d 次，原因=%s）。",
            getattr(agent, "name", "?"),
            state.retries,
            state.pending_problem or "empty",
        )
        hint_text = self._retry_hint_text(state)
        try:
            agent.state.append_context(
                agent.name,
                [
                    HintBlock(
                        hint=[TextBlock(type="text", text=hint_text)],
                        source='{"label": "System"}',
                    ),
                ],
            )
        except Exception:  # noqa: BLE001 —— 塞提示失败也要继续，见下
            # ⚠️ 这里**不向上抛**：本轮已经决定重试（事件已吞），此时抛异常
            # 会让整条回复以 error 结束，比「模型没收到提示、原样再答一遍」
            # 更糟。原样再答一遍至少还有一次成功的机会。
            logger.exception("回复守卫塞入纠正指令失败，本轮重试可能原地踏步。")

    @classmethod
    def _ungrounded_limit_offenders(
        cls,
        agent: Any,
        state: _ReplyState,
        text: str,
    ) -> list[str]:
        """这段正文里「断言了工具没给过的差标上限」的数值。

        Args:
            agent (`Any`): agent 实例（取「动态 Prompt 注入过的数字」）。
            state (`_ReplyState`): 回复状态（提供工具返回与工具名）。
            text (`str`): 剥离后的候选正文。

        Returns:
            `list[str]`: 命中的数值；没命中返回空列表。

        ⚠️ 这是闸门**唯一**的判据入口 —— :meth:`_settle_round`（拦下本次
        正文）与 :meth:`_fallback_if_silent`（拒绝复活草稿）都走它。
        写成两套判据的话，闸门会一边拦一边放，而症状是「编造的数字偶尔
        还是发得出去」—— 那正是最难查的一类 bug。

        ⚠️ 两个先决条件写在**这里**而不是调用方，同样是为了同源：
        调过差标工具（否则知识库分档值会被误伤）、且**这一轮的文字有可能
        已经被工具返回支持**。

        ⚠️ 第二个条件 2026-10-04 收紧了（缺陷代号 F2）。当时的写法是
        ``not state.tool_text -> return []``，依据是「工具文本为空 = 工具
        没给过这个数」；那是个**错的前提**，因为框架的事件顺序决定了
        「工具文本为空」还有另一个含义：

            ModelCallEndEvent    （本轮文字在此结算，下面这个闸门也在此跑）
            ToolCallStartEvent   ← 已在本轮更早发出（分块流式时），
                                    所以 state.round_tools 此刻是齐的
            ToolResultTextDeltaEvent  ← **在本轮 ModelCallEndEvent 之后**
                                        才到（``_agent.py`` 里 Reasoning
                                        先于 Acting），所以本轮的返回文本
                                        在结算时**必然还没进 tool_text**

        于是「本次回复的**第一轮**就调了差标工具」这一最常见的情形
        恰好落在旧条件的空档里：tool_text 为空 → 整个闸门短路 → 模型在
        看到工具返回**之前**写下的数字（纯粹的先验）原样放行。

        现场复现（假想的先验值 500，工具实际返回 600）：同一轮里
        ``check_travel_policy``（只读）与 ``submit_approval``（写）一起
        被调用 → 这一轮的文字按「给用户看的复述」保留 → 用户看到的确认
        信息里写着「酒店差标是 500 元/晚」。旧条件在两个方向上都不成立：
        它既不是「没调过差标工具」，也不是「工具给了文字」。

        修法：工具文本为空时**再问一句**「本轮调的就是差标工具吗」——
        是，则这段文字在写下时不可能有任何依据，闸门必须跑（这不是
        「工具没返回文字」，而是「返回还没到，正文先写了」）；不是，
        才维持旧行为（没有工具文本、又不是差标工具轮，闸门无从判断，
        宁可不动 —— ``test_limit_gate_is_off_when_no_tool_text_arrived``
        钉的就是这一支）。
        """
        if not state.policy_tools:
            return []
        if not state.tool_text and not any(
            name in _POLICY_LIMIT_TOOLS for name in state.round_tools
        ):
            return []
        # ⚠️ 第四个合法来源：**我们自己**注入进 prompt 的那部分用户数据里的
        # 数字（2026-10-04 缺陷 P1）。它必须按 ``reply_id`` 校验新鲜度，
        # 不能拿上一条回复的登记当豁免 —— 那一侧的口子开在「放走编造」上。
        prompt_numbers = recorded_prompt_numbers(
            agent,
            cls._resolve_reply_id(agent, state),
        )
        return _ungrounded_limit_claims(
            text,
            "".join(state.tool_text),
            state.user_text,
            " ".join(prompt_numbers),
        )

    @staticmethod
    def _retry_hint_text(state: _ReplyState) -> str:
        """按被拒原因挑一条纠正指令。

        Args:
            state (`_ReplyState`): 回复状态。

        Returns:
            `str`: 要塞进模型上下文的纠正指令。

        ⚠️ 两种原因对应两套**完全不同**的指令，不能合并成一条：
        「只写了内心独白」要它「直接给结论」，而「编了差标数值」要它
        「回去读工具返回」—— 把后者丢给前者会答非所问，模型读完第一条
        仍然不知道自己的数字有问题。
        """
        if state.pending_problem == "ungrounded_limit" and state.ungrounded_limits:
            return _UNGROUNDED_HINT_TEMPLATE.format(
                amounts="、".join(state.ungrounded_limits[:5]),
            )
        return _RETRY_HINT

    def _fallback_if_silent(
        self,
        agent: Any,
        state: _ReplyState,
    ) -> list[EventBase]:
        """重试用尽后仍无正文时，补一段兜底正文。

        Args:
            agent (`Any`): agent 实例（解析 ``reply_id`` 用）。
            state (`_ReplyState`): 回复状态。

        Returns:
            `list[EventBase]`: 要补发的文本事件；已经发过正文时返回空列表。

        ⚠️ 兜底优先用**模型自己写过的最后一版草稿的剥离结果**，而不是直接上
        固定话术：草稿里往往有真答案（实测的 B[3] 就是「七段独白 + 四段正文」），
        剥离后通常就能用。只有在草稿也救不回来时才用固定话术 ——
        那意味着这轮确实没有任何可用内容。

        ⚠️ 未被回收的草稿只有**能通过 ``_answer_problem`` 检查的**才发得出去
        （见 ``_answer_problem`` 的三类拒绝）。所以「把刚丢掉的工具轮前言
        当成答复发出去」只会发生在它剥离后**确实是一段可用正文**的时候 ——
        那正是我们想要的回收，不是漏网。已知的残留风险是「单段、无数字、
        又恰好不被 ``_is_draft`` 认出来的过程叙述」会被当成兜底发出去
        （例如「让我看看能不能帮你订。」）：判据表是**已知形状表**，
        换种说法就漏，这一点写在模块文档「能力边界」里。
        """
        if state.emitted:
            return []
        reply_id = self._resolve_reply_id(agent, state)
        for draft in reversed(state.drafts):
            cleaned, _ = _strip_drafts(draft)
            if _answer_problem(cleaned) is not None:
                continue
            if cleaned.strip() in state.blocked_texts:
                # ⚠️ 这段正文**已经被闸门拦过一次**，不再考虑（2026-10-04
                # 缺陷 F4）。判据必须落在这个「既往记录」上，而不是重新跑
                # 一次 :meth:`_ungrounded_limit_offenders` —— 那个判据是
                # **非单调**的：它拿 ``state.tool_text`` 当事实基准，而
                # tool_text 会随重试轮继续增长。实测到的复活链：
                #
                #   第 1 轮  调差标工具 + 正文写「差标是 500 元」→ 拦下
                #   第 2 轮  模型把 500 当成参数**传进工具**
                #   第 2 轮的返回里出现了 500（工具回显了入参）
                #   → tool_text 里「有」500 了，同一个判据对同一段文本
                #     给出「有依据」—— 兜底把它原样发给了用户
                #
                # 「被模型写进参数、又被工具回显」不等于工具**认定**这个数，
                # 但对判据来说两者长得一样。既往记录是唯一不受这个影响的
                # 依据：拦过的就是拦过的，重试期间工具文本怎么长都不翻案。
                #
                # ⚠️ 只在兜底这里生效，**不**回写进 settle 的判据：重试轮里
                # 模型是**看过**工具返回之后重写的，同一段文本此时可能确实
                # 有依据了（例如它第一轮猜对了 600），照常放行是预期行为。
                # 这里防的是「兜底把闸门刚拦下的东西当答案发出去」，不是
                # 「同一段文本永远不许出现」。
                observe_reply_guard("fallback_skipped_ungrounded")
                logger.warning(
                    "回复守卫放弃一段**已被闸门拦下过**的草稿兜底（长度 %d）。",
                    len(cleaned),
                )
                continue
            if self._ungrounded_limit_offenders(agent, state, cleaned):
                # ⚠️ 被事实接地闸门拦下的草稿**不能**在这里复活。
                # 否则「拦 → 重试 → 重试用尽 → 兜底」这条链的终点会是
                # **同一段编造的正文**被原样发给用户 —— 闸门拦了个寂寞，
                # 还把延迟推高了。宁可退回固定话术（承认这轮没答好），
                # 也不能把一个会误导用户去报销的数字发出去。
                observe_reply_guard("fallback_skipped_ungrounded")
                logger.warning("回复守卫放弃一段无依据的草稿兜底（数值=%s）。", state.ungrounded_limits[:5])
                continue
            observe_reply_guard("fallback_from_draft")
            logger.warning("回复守卫用最后一版草稿兜底（长度 %d）。", len(cleaned))
            state.emitted_text += cleaned
            return _synth_text_events(
                reply_id,
                cleaned,
                self._next_block_id(state, "guard-fallback"),
            )
        observe_reply_guard("fallback_generic")
        logger.warning("回复守卫用固定话术兜底（本次回复没有任何可用内容）。")
        state.emitted_text += _FALLBACK_TEXT
        return _synth_text_events(
            reply_id,
            _FALLBACK_TEXT,
            self._next_block_id(state, "guard-fallback"),
        )

    # --------------------------------------------------------------------------
    # 收尾上报
    # --------------------------------------------------------------------------
    def _report(self, state: _ReplyState) -> None:
        """回复结束时上报「本模块解决不了的那部分」。

        Args:
            state (`_ReplyState`): 回复状态。

        两件事：

            1. 统计**残留可疑段落**（段落中间的草稿、被保留下来的确认复述）；
            2. 统计**疑似无依据的金额**（见 :func:`_ungrounded_amounts`）。

        ⚠️ 两件都**只上报，不改变行为**。理由见模块文档「能力边界」——
        在拿到真实的误报率之前就拦截，会把正确答案也改坏。

        ⚠️ 审的是 ``emitted_text``（**用户实际看到的那段**），不是被丢掉的草稿。
        写错过一次：早先的版本拿 ``drafts`` 去查无依据金额，等于「只检查扔掉的
        垃圾、放过端上桌的菜」—— 而实测那次编造（工具说 600、模型写 500）
        恰恰出现在发给用户的正文里。
        """
        answer = state.emitted_text
        if not answer.strip():
            return
        classes = _classify_suspicious_paragraphs(answer)
        for kind in sorted(classes):
            observe_reply_guard(f"draft_paragraph_left_{kind}")
        if classes:
            logger.info(
                "回复守卫：发给用户的正文里仍有 %d 段可疑内容（%s）。",
                sum(classes.values()),
                "、".join(f"{kind}={count}" for kind, count in sorted(classes.items())),
            )
        ungrounded = _ungrounded_amounts(answer, "".join(state.tool_text))
        if ungrounded:
            observe_reply_guard("ungrounded_amount")
            logger.warning(
                "回复守卫：答复里的金额 %s 未在同轮工具返回中出现，请人工复核。",
                ungrounded[:5],
            )
