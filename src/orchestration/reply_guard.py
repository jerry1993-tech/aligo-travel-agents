    _MARKER_CLEANUP_VERBS
    + r"|clean(?:ed|ing|s)?"
    # ⚠️ ``e`` 不能漏：``purg(?:ed|ing|es)?`` 认不出**原形** ``purge``
    # （2026-10-05 第三轮对抗验证 #19 的补测实测：``[tool_result purge]``
    # 既不剥也不计）。其余几个动词的原形恰好等于词干，没有这个坑。
    r"|purg(?:e|ed|ing|es)?"
    r"|flush(?:ed|ing|es)?"
    r"|trim(?:med|ming|s)?"
    r"|evict(?:ed|ing|s)?"
