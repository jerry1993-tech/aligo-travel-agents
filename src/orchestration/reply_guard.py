#: 往往是**核对**的语气（「600 元封顶」也有，但少）。
#:
#: 对称的 12 字符窗口实测会误伤这句**正确**的回答::
#:
#:     500 元没超过 600 的上限，可以报。
#:
#: 「上限」距离 500 只有 9 个字符，于是用户自己报的 500 被判成编造。
