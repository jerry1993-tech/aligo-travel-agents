#:     酒店差标是 **500 元/晚**，系统里不区分一类、二类城市。
#:
#: 工具返回的是 600，正文写 500 —— 一句彻底的编造。而当时的词表里
#: 没有「差标」，500 之前 8 个字符是「酒店差标是 **」，一个词都没命中，
#: 闸门**整条放行**。所以补进「差标」「标准」「额度」「限价」。
#:
#: ⚠️ 早先的注释说「刻意不收『标准』这类泛词，怕把核对句卷进来」。那个
#: 顾虑是真的，但**解法不是不收录，而是把「有合法来源的数字」排除掉**
#: （见 ``_ungrounded_limit_claims`` 的三个来源）——
#: 「我订了 500 的能报吗」里的 500 是用户给的，「两晚标准合计 1200」里的
#: 1200 是 600×2 算出来的，两者都不是编造，从源头排除即可。
#: 靠缩小词表来规避误伤，代价是真正的编造（就是上面那句）大摇大摆地过去。
#:
#: ⚠️ 「标准」这个词确实带来了最大的误伤面（2026-10-03 对抗验证实测：
#: 「两晚住宿标准合计 1200 元」被拦、重试耗尽后用户只看到一句兜底道歉），
#: 但那次误伤的**根因是缺了「合计」这一合法来源**，不是词表收了「标准」——
#: 把词删掉只会让「差标是 500」这类真编造重新漏网。修因不修表。
#:
#: ⚠️ 仍然**不收**「报销」「能报」这类**动作**词：它们描述的是「能不能报」，
#: 与「上限是多少」不是一回事，收进来只会扩大误伤面。
_LIMIT_WORDS: Final[tuple[str, ...]] = (
    "上限",
    "限额",
    "限价",
    "不超过",
    "不得超过",
    "封顶",
    "以内",
    "最高",
    "差标",
    "标准",
    "额度",
)

#: 「标准」后面跟这些字时，它是在说**房型**，不是在说上限。
#:
#: ⚠️ 2026-10-03 对抗验证实测到的误伤（这两句都是**正确**回答）::
#:
#:     可以订标准间，500 元一晚。
#:     标准间 500 元一晚可以订。
#:
#: 两句里的 500 都被判成编造 → 拦下 → 重试 → 重试耗尽后用户只看到一句
#: 兜底道歉。而「标准间 / 标准房 / 标准双床房」是中文里极常见的房型说法，
#: 与「上限」的含义毫无关系 —— 这是**同形不同义**，只能靠右侧搭配区分。
#:
#: ⚠️ 这条路**只对「标准」开**。其余词（上限/差标/额度…）没有这种双重身份，
#: 给它们也加搭配判断只会让判据变复杂且没有收益。
#:
#: ⚠️ 排除面刻意收得很窄：只认「标准」**紧邻**这几个字。放宽（比如允许
#: 中间隔字）会重新打开真编造的漏检口子，而「住宿标准 500 元」这类句子
#: 正是这条闸门存在的理由。
_STANDARD_ROOM_HEADS: Final[tuple[str, ...]] = (
    "间",
    "房",
    "双床",
    "大床",
    "单间",
    "套间",
)

#: 金额**之前**多少字符内出现 :data:`_LIMIT_WORDS` 才算「在说上限」。
#:
#: ⚠️ 两侧**刻意不对称**：中文里定义上限的词几乎都在数字**前面**
