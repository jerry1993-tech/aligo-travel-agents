#: 「模型在对谁说话」的判据 —— 命中即认为这一段是**写给自己的**，不是给用户的。
#:
#: ⚠️ 这些都是**段首**匹配（对去掉 markdown 记号后的段首）。之所以不敢做
#: 「包含即命中」，是因为「我」开头的正经答复不少（「我帮你查了一下，北京…」），
