_LIMIT_LOOKBEHIND: Final[int] = 8

#: 金额**之后**多少字符内出现 :data:`_LIMIT_WORDS` 才算「在说上限」。
_LIMIT_LOOKAHEAD: Final[int] = 4

#: 重试前必须留有的 ReAct 迭代余量。
