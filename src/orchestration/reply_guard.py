_numbers_in = numbers_in




def _is_derived_total(normalized: str, tool_numbers: set[str]) -> bool:
    """判断一个数是不是「工具返回里的某个数 × 小整数」算出来的合计。

    这是本模块早就承认的第三种合法来源（见 :func:`_ungrounded_amounts`
    的文档：「模型算出来的合计（1200 = 2×600）」）。2026-10-03 由对抗
    验证实测出来：缺少这一条时，「两晚住宿标准合计 1200 元」这类**正确**
    的回答被判成编造 —— 而闸门拦下正确回答的代价是重试、重试耗尽后
    用户看到的是一句兜底道歉。

    ⚠️ 只认**乘法**（单价 × 数量），不认加法/减法/除法，原因是覆盖面与
    误伤面的权衡：加减法能「凑」出的数字太多（任何两个工具数字的和都是
    合法来源），而除法没有任何业务含义（没人会拿差标去除以 3）。
    乘法的乘数限制在 2..9，理由同上 —— 再大就不是「几晚/几张」了。

    ⚠️ 这条会**故意放过**一类编造：把 2×600 的合计写成「差标是 1200 元」。
    判据是「这个数算不算得出来」，而 1200 确实算得出来。要区分
    「合计」与「上限断言」得有语义理解，代价远大于收益 —— 且这种漏报
    仍会被 :func:`_ungrounded_amounts` 的**上报**记录在案。

    Args:
        normalized (`str`): 归一后的数字串。
        tool_numbers (`set[str]`): 本轮工具返回里出现过的数字。
            ⚠️ 必须来自工具，不能把用户原话并进来 —— 否则用户随口说的
            一个数乘以 2 就成了「依据」。

    Returns:
        `bool`: 是算出来的合计返回 ``True``。
    """
    try:
        value = float(normalized)
    except ValueError:  # pragma: no cover —— _normalize_amount 的产物必可转
        return False
    for base in tool_numbers:
        try:
            base_value = float(base)
        except ValueError:  # pragma: no cover —— 同上
            continue
        if base_value <= 0:
            continue
        ratio = value / base_value
        if 2 <= ratio <= 9 and abs(ratio - round(ratio)) < 1e-9:
            return True
    return False


def _is_a_room_type(window: str, idx: int) -> bool:
    """``window[idx:]`` 以「标准」开头时，判断它是不是**房型名**。

    Args:
        window (`str`): 金额周围的窗口文本。
        idx (`int`): 「标准」在 ``window`` 里的起始下标。

    Returns:
        `bool`: ``True`` 表示这是「标准间 / 标准房 / 标准双床房」这类房型。

    ⚠️ 只认**紧邻**的搭配字。允许中间隔字（比如「标准双人大床房」）会同时
    把「住宿标准 500 元」的变体也放行 —— 而后者正是这条闸门存在的理由。
    宁可漏放几个生僻房型说法，也不放开真编造。
    """
    tail = window[idx + len("标准"):]
    return any(tail.startswith(head) for head in _STANDARD_ROOM_HEADS)


def _mentions_a_limit(window: str) -> bool:
    """窗口里有没有「在说上限」的措辞。

    Args:
        window (`str`): 金额周围的窗口文本。

    Returns:
        `bool`: ``True`` 表示这个金额出现在一句**陈述上限**的话里。

    ⚠️ 与「``any(word in window for word in _LIMIT_WORDS)``」的差别只有一处：
    「标准」要看**右邻搭配**再决定算不算上限措辞（见
    :data:`_STANDARD_ROOM_HEADS` 与 :func:`_is_a_room_type`）。
    其余词一律照旧 —— 它们没有「同形不同义」的问题。
    """
    for word in _LIMIT_WORDS:
        start = 0
        while (idx := window.find(word, start)) >= 0:
            if word == "标准" and _is_a_room_type(window, idx):
                # 这个词是房型名的一部分，继续找**下一个**「标准」——
                # 「标准间 500 元，住宿标准也是 500」这种句子里，
                # 后一个「标准」仍然要能命中。
                start = idx + len(word)
                continue
            return True
    return False


def _ungrounded_amounts(answer: str, tool_text: str) -> list[str]:
    """列出答复里「工具返回中没有出现过的金额」。

    Args:
        answer (`str`): 发给用户的正文（已剥离草稿）。
        tool_text (`str`): 本次回复内所有工具返回文本的拼接。

    Returns:
        `list[str]`: 疑似没有依据的金额字符串（去重、保持出现顺序）。

    ⚠️ **这是启发式，不是判据** —— 结果只进日志和指标，不参与任何拦截。
    误报来源一大堆：用户自己给的金额、模型算出来的合计（1200 = 2×600）、
    叙述性的「两晚」等。反过来漏报也有：工具返回 600、模型写「六百」。
    它的价值在于**把「模型编数」从一个查不到的传说变成一条能画曲线的
    指标** —— 没有这条曲线，就无法判断该不该做更强的忠实性校验。

    ⚠️ 比对方式与 :func:`_ungrounded_limit_claims` 一致：**按完整数字
    比对，不做子串包含**（理由见 :func:`_numbers_in`）。这里多抓一点
    没关系（反正只上报），但不能因为「2000 包含 200」这种巧合而**漏抓**。
    """
    if not answer:
        return []
    # ⚠️ 折全角必须在**取偏移之前**（见 _fold_width）：下面的窗口切片用的是
    # 折过之后的字符串，两者必须同源，否则「上限」这个词会飘出窗口。
    answer = _fold_width(answer)
    tool_numbers = _numbers_in(tool_text)
    found: list[str] = []
    for match in _AMOUNT_PATTERN.finditer(answer):
        raw = (match.group(1) or match.group(2) or "").strip()
        if not raw:
            continue
        normalized = _normalize_amount(raw)
        if normalized in tool_numbers:
            continue
        if raw in found or normalized in found:
            continue
        found.append(raw)
    return found


def _ungrounded_limit_claims(
    answer: str,
    tool_text: str,
    user_text: str = "",
    prompt_text: str = "",
) -> list[str]:
    """列出答复里「断言了一个上限、但这个数不在本轮工具返回里」的金额。

    与 :func:`_ungrounded_amounts` 是**两个不同的问题**，别合并：

    - ``_ungrounded_amounts`` 问的是「这个数在工具返回里出现过吗」，
      它把**所有**金额都算进来（用户自己报的价、模型算的合计……），
      因此误报极多，只能上报。
    - 本函数问的是「这句在**断言差标**吗」——只有同时满足
      「像是一个金额」+「紧挨着上限措辞」+「四个合法来源里都没有」才判定
      命中。条件更窄，因此可以拿来做拦截。

    ⚠️ **调用方必须先确认本次回复真的调过差标工具**
    （:data:`_POLICY_LIMIT_TOOLS`）。否则知识库检索出来的分档数字
    （一类城市还有 800、1200 这些档）会被判成「无依据」——
    那是**正确**的答复被改坏，比放过一次编造更糟。

    **四个合法来源**（任何一个命中就放行，按比对顺序）：

        1. 本轮工具返回里出现过这个数 —— 判据的基准；
        2. 用户本轮自己说过这个数 —— 「我订了 500 的能报吗」；
        3. 是工具返回里的某个数乘小整数算出来的合计（1200 = 2×600）——
           见 :func:`_is_derived_total`；
        4. **我们自己**在动态 Prompt 里注入过的、承载用户数据的数字
           （``prompt_text``）—— 即来源 2 的「跨轮」形式，见下。

    ⚠️ 来源 4 是 2026-10-04 补的（缺陷代号 P1）。前三个来源都只看**本轮**：
    用户在前一轮报过「预算 15000」，此后每一轮的动态 Prompt 都会把
    「预算上限：15000 元」写进 system prompt（
    :func:`~src.orchestration.prompt.describe_known_slots`），模型照抄这句
    **完全正确**的话，却因为「本轮用户文本里没有 15000」被判成编造 ——
    拦下 → 重说 → 模型坚持引用 → 用户最终收到一句道歉兜底。
    实测过的措辞敏感度：写「预算上限：15000 元」会被拦，写「预算是 15000 元」
    则不会（后者不满足 ``_mentions_a_limit`` 的「上限」措辞前提）——
    这正是最坑的一种：闸门并非「总是拦」，而是取决于模型怎么措辞。

    ⚠️ 来源 4 的文本**必须来自登记**，不能由调用方随手传
    （``ContextInjectionMiddleware`` 把「自己拼进 prompt 的用户数据」的
    数字记进 ``agent.state.middle_context``，见
    :func:`src.orchestration.context.recorded_prompt_numbers`）。
    传「整个 system prompt」会把阶段指令这类静态文案里的数字也算成豁免，
    闸门白白放宽。

    ⚠️ 四者**全部按完整数字比对**（先经 :func:`_normalize_amount` 归一），
    绝不退回子串包含 —— 历史上正是子串匹配让「用户说 5000 → 答复写 500」
    和「工具返回 2000 → 答复写 200」两种编造同时漏网。

    Args:
        answer (`str`): 本轮候选正文。
        tool_text (`str`): 本次回复内所有工具返回文本的拼接。
        user_text (`str`): 用户本轮说过的话。**用户自己报过的数字不算编造** ——
            「我订了 500 的能报吗」→ 回答「按你的差标，500 元以内可以报」，
            这里的 500 有合法来源，拦下来会把一次**正确**的回答改坏。
            默认空串：取不到用户原话时行为与不传一致（只会更保守，
            不会更激进）。
        prompt_text (`str`): 本轮动态 Prompt 里**承载用户数据**的那段文本
            （见来源 4）。默认空串：不传时行为与没有来源 4 一致 ——
            只会更保守，不会更激进。

    Returns:
        `list[str]`: 疑似无依据的上限数值（去重、保持出现顺序）。

    ⚠️ 仍是启发式：它抓得住「工具说 600、正文写 500 元上限」，
    抓不住「六百」（中文数字）。它的定位是**兜底闸门**，不是完备校验 ——
    真正的修复在提示词的溯源条款里。
    """
    if not answer:
        return []
    # ⚠️ 折全角必须在**取偏移之前**（见 _fold_width）：下面
    # ``match.start()/_mentions_a_limit`` 的窗口切片用的是折过之后的字符串。
    answer = _fold_width(answer)
    # 合法来源之一：本轮工具返回里出现过的数。
    tool_numbers = _numbers_in(tool_text)
    # 合法来源之二：用户自己说过的数。
    user_numbers = _numbers_in(user_text)
    # 合法来源之四：我们自己在动态 Prompt 里注入过的、承载用户数据的数。
    # ⚠️ 一定要走 _numbers_in 再比一遍，而不是直接拿登记里的字符串做集合 ——
    # 登记侧写的是**归一后**的数，而这里比对的也是归一后的数，两边同源；
    # 但登记是**持久化**数据，可能由旧版本代码写下（归一规则改过），
    # 再过一遍归一是最便宜的兼容手段。
    prompt_numbers = _numbers_in(prompt_text)
    found: list[str] = []
    for match in _AMOUNT_PATTERN.finditer(answer):
        raw = (match.group(1) or match.group(2) or "").strip()
        if not raw:
            continue
        normalized = _normalize_amount(raw)
        # ⚠️ 四处比对**全部按完整数字**，一处都不能退回子串包含。
        # 这里出过两个方向相反的实测缺陷（2026-10-03，对抗验证复现）：
        #   · 用户说「预算是 5000」，答复写「差标是 500」→ 子串命中，
        #     编造被当成「用户说过的数」放行；
        #   · 工具返回里有 2000（机票差标）时，``"200" in "2000"`` 为真，
        #     同一句编造又变成「有依据」。
        # 两次都是「子串恰好套住了」造成的，所以判据必须落在数字边界上。
        # 工具返回里出现过 —— 有依据，放行。
        if normalized in tool_numbers:
            continue
        # 用户自己说过这个数 —— 不是编造，放行。
        if normalized in user_numbers:
            continue
        # 我们自己在 prompt 里给过的数 —— 用户说过的数的跨轮形式，放行。
        if normalized in prompt_numbers:
            continue
        # 是工具返回里的某个数乘出来的合计（1200 = 2×600）—— 有依据，放行。
        # 只在工具数上算：用户随口说的数乘 2 不构成依据。
        if _is_derived_total(normalized, tool_numbers):
            continue
        window_start = max(0, match.start() - _LIMIT_LOOKBEHIND)
        window_end = min(len(answer), match.end() + _LIMIT_LOOKAHEAD)
        if not _mentions_a_limit(answer[window_start:window_end]):
            continue
        if raw in found or normalized in found:
            continue
        found.append(raw)
    return found


