#:       —— 确认复述被判成独白，整轮被拒 + 一次**归因错误**的重说
#:       （提示词说「你只输出了思考过程」，而它输出的是复述）。
#:     · 「根据上海的规定…」—— 原文 ``^根据(我的|工作方式|上)`` 只写了单字
#:       「上」，于是所有以「根据上…」开头的句子（含地名「上海」）都命中；
#:       「这是标准双床房」「我需要提醒您…」同理。
#:
#: ⚠️ 删掉不等于放弃这一类：它们要抓的「自我盘算」由
#: :data:`_META_COMMENTARY_MARKERS`（「我应该」「我需要先」「接下来我」）与
#: :data:`_THIRD_PERSON_PLANNERS` 接着 —— 那两条是**段中出现**匹配，
#: 比段首匹配更严格也更准（实测的 B[6] 段落同时被两边命中，删了段首这条
#: 照样抓得住）。段首这几条的**收益**只是「同一段被两条判据同时认出来」，
#: 代价却是把结论句和复述整段删掉 —— 这笔账在本模块的取态下是亏的。
_MONOLOGUE_OPENERS_STRONG: Final[tuple[re.Pattern[str], ...]] = tuple(
    re.compile(pattern)
    for pattern in (
        r"^I (need|should|must|have to|want to|am going to|plan to|will)\b",
        r"^I'(ll|m going to|d better)\b",
        r"^Let me (first|check|look|verify|see|query|search|find|call)\b",
        r"^The user\b",
        r"^Now I\b",
        r"^用户(问|想|说|要|在问|询问|提到|需要|这里|既然)",
    )
)

#: ⚠️ **弱档**：形状上像过程叙述，但与政策类答复的**结论句**共用开头。
#: 只在**段首剥离**里用（那里的误伤可逆）；结尾剥离不许用 —— 理由见
#: :func:`_is_draft` 的「分档」一节。
#:
#: ⚠️ 2026-10-04 从强档降下来两条（对抗验证逐条复现）：
#:
#:     ``^系统(已经|已)``     ``^当前(处于|阶段|我)``
#:
#: 它们描述的是**状态**，而「状态已经变成什么样」恰恰是给用户的结论句
#: 常见开头：
#:
#:     · 「系统已经为您提交了申请，请等待审批。」
#:     · 「系统已经为您核对完成，请稍候。」  ← 这句更危险，见下
#:
#: 放在强档等于承诺「答复里不可能以它们开头」——这个承诺是假的。落在
#: **结尾**的段落一旦被误删**不可逆**（正文已发，没有重说兜底），删掉的
#: 又是一句结论。降到弱档之后：段首剥离照旧（误伤可逆）、
#: ``_answer_problem`` 照旧（全表），只有**结尾删除**收手。
#:
#: ⚠️ 别把它们直接从表里删掉。那句「系统已经为您核对完成，请稍候。」是
#: 一句**纯状态话术**：删掉判据之后 :func:`_is_placeholder` 与
#: :func:`_answer_problem` 都会放行它，用户会拿到一句「正在核对」当答复
#: （实测）。降档保留了这个拦截：全表（``_MONOLOGUE_OPENERS``）里还有它。
_MONOLOGUE_OPENERS_WEAK: Final[tuple[re.Pattern[str], ...]] = tuple(
    re.compile(pattern)
    for pattern in (
        r"^现在我看",
        r"^系统(已经|已)",
        r"^当前(处于|阶段|我)",
    )
)

#: 全表：段首剥离、``_answer_problem`` 都用它（强档 + 弱档）。
#:
#: ⚠️ 两档都在这里，是为了让「哪几条在结尾也能用」这件事**写在数据上**：
#: 新加一条时要么进强档（承诺「答复里不可能出现」），要么进弱档。
_MONOLOGUE_OPENERS: Final[tuple[re.Pattern[str], ...]] = (
    _MONOLOGUE_OPENERS_STRONG + _MONOLOGUE_OPENERS_WEAK
)

#: 「这段话在讲自己的打算/过程」的判据 —— **段中出现**即命中。
#:
#: 与 :data:`_MONOLOGUE_OPENERS` 的区别：这些词组在**给用户的正文**里几乎
#: 不会出现（没人会对用户说「我应该直接给出这个结论」），所以可以做包含匹配。
#: 它专门用来抓「第一段是独白、但后半段又混进了数字」那种半吊子段落
#: （实测 B[6] 的第二段就是：「现在我看清楚了标准：酒店单晚不超过600元…
#: 我应该直接给出这个结论…」）。
_META_COMMENTARY_MARKERS: Final[tuple[str, ...]] = (
    "我应该",
    "我不该",
    "我不应该",
    "我需要先",
    "我先把",
    "我原本要",
    "我这就去",
    "接下来我",
    "结论先行给用户",
    "这样既回答",
    "让政策问答",
    "去检索制度原文",
)

#: 「宣布要去查、但没说查到了什么」的判据 —— **段首**匹配 + 数字保险丝。
#:
#: ⚠️ 为什么单独立一条：它单看**像**答复（「我先查一下差标。」），而实测的
#: C 类缺陷（「已让政策问答智能体检索制度原文，稍等。」）是同一个毛病的另一种
#: 说法 —— 模型宣布了一个它**没有执行**的动作就结束回合，用户拿到一句空话。
#: 工具轮里的这类句子已经被「工具轮文字 = 草稿」接住了；但模型**不调工具、
#: 只写一句「我先查一下」**的时候，只有这条能拦住 —— 而那正是最气人的形态，
#: 因为用户会以为它在查，然后就没有然后了。
#:
#: ⚠️ 两道保险丝（这是本表唯一一条带保险丝的判据，因为它的误报面最大）：
#:
#:     1. **段首**匹配（``^``）—— 「…所以我先查一下」这种半句不在此列；
#:     2. 段内**没有任何数字**才判草稿 —— 有数字说明结果已经带回来了
#:        （「我先看下你的订单状态：已提交，共 2 晚」不该被剥）。
#:
#: 残留风险：一段**没有数字、又以「我先查…」开头**的正经答复会被误判，
#: 代价是触发一次重说。取舍理由：那个形状几乎只出现在「宣布动作」里，
#: 而它漏出去的后果正是我们要消灭的 C 类缺陷。
#:
#: ⚠️ 这个洞是**写单测时发现的**（``tests/test_orchestration_reply_guard.py``
#: 的 ``test_measured_draft_paragraphs_are_recognized`` 抓到的第一版漏网），
#: 不是线上观测到的 —— 记在这里是为了说明：判据表的边界要靠对着真实文本
#: 一条条试，不能靠「应该够了吧」。
_ANNOUNCED_ACTION_OPENERS: Final[re.Pattern[str]] = re.compile(
    # ⚠️「让我」这一支是 2026-10-03 补的：原表只有第一人称 ``我``，
    # 于是「让我先查一下差标。」——一个人称换了个字的同款空话——
    # 从判据里整个漏掉（实测 ``_is_draft`` 返回 False）。
    # ``(?:我|让我)`` 的顺序不影响正确性：文本以「让」开头时第一支不匹配，
    # 自然落到第二支。
    r"^(?:我|让我)(先|来|去)?(查|检索|找|确认|看一下|看下|看看|翻|调)",
)

#: 「动作已经做完了」的收尾 —— 出现在 :data:`_ANNOUNCED_ACTION_OPENERS`
#: 动词组**紧后面**时，那句话是**完成陈述**而不是打算。
#:
#: ⚠️ 为什么需要这个：判据只问「是不是以『我(先)查…』开头」，而
#: 「我先确认**了**订单和发票信息，都齐全。」与「我先确认**一下**差标。」
#: 的前缀一模一样。前者是**完整的答复**，后者是**空话**。
#: 实测前者被整段判成草稿 → ``_answer_problem`` 返回 ``monologue`` →
#: 触发重说，重试用尽时用户看到的是兜底道歉而不是答案。
#:
#: ⚠️ 用「动词后紧跟 了/过」做判据是一个**代理判据**，不是语义理解：
#: 它抓的是汉语里最稳的那条形态线索（完成体标记紧跟动词）。
#: 残留风险写在 :func:`_is_draft` 的 docstring 里。
_COMPLETED_ACTION_SUFFIXES: Final[tuple[str, ...]] = ("了", "过")

#: 「这段文字里有没有数量信息」的判据用的字符集 —— **只认阿拉伯数字**。
#:
#: ⚠️ 中文数字（六百元 / 两晚 / 三档）**刻意不算**。试过把它们加进来，结果
#: 是判据当场失效：
#:
#:     · 「稍等**一**下」→ 被判成「有数量信息」⇒ 占位符判据放行了一句纯空话；
#:     · 「我先查**一**下差标」→ 被判成「有数量信息」⇒ 保险丝反过来
#:       把它从草稿里放了出去，而它正是这条规则要抓的头号形状。
#:
#: 「一下 / 一遍 / 一眼」这类固定搭配里的中文数字是虚词，不是数量。
#: 要精确区分就得做分词，而分词的成本远大于它挡住的那点误报 ——
#: 所以这里的取舍是：**只认阿拉伯数字**，中文数字带来的漏报（一段
#: 用中文数字写成的短答复被当成草稿）记在模块文档「能力边界」里。
#:
#: ⚠️ 用 ``isdecimal()`` 而不是 ``isdigit()`` —— 这两个谓词**不等价**，
#: 而差的那部分恰好全是坑：``'①'.isdigit()`` 与 ``'²'.isdigit()`` 都是
#: ``True``，``'①'.isdecimal()`` / ``'²'.isdecimal()`` 才是 ``False``。
#: 于是「稍等①」「我先查一下²」这种文本会让保险丝失效，把一句纯空闲话
#: 放行成答复。而 :data:`_NUMBER_TOKEN_PATTERN` 用的 ``\d`` 在 Python 里
#: 正好等价于 ``isdecimal()`` —— 改过来之后，本模块里「什么算数字」
#: 三处口径（此处的字符谓词、正则的 ``\d``、金额比对的归一化）终于一致。
def _has_quantity(text: str) -> bool:
    """判断文本里有没有阿拉伯数字（即「带回来了具体数据」的弱信号）。

    Args:
        text (`str`): 待检查的文本。

    Returns:
        `bool`: 含任一阿拉伯数字字符时返回 ``True``。
    """
    return any(char.isdecimal() for char in text)


#: 「N 分钟后 / 等 3 秒」这类**时间估计**。
#:
#: ⚠️ 它存在的唯一理由是给「有数字就说明结果已带回」这条保险丝打补丁：
#: 时间估计里的数字**不是**带回来的数据，但长得一模一样。实测漏网的一句是
#: 「稍等，预计 2 分钟后给你结果。」—— 它含数字，于是占位符判据当场放行，
#: 用户屏幕上就停在这一句，没有下文。把时间估计里的数字先抠掉再判，
#: 这句才被正确识别成占位。
#:
#: ⚠️ 只匹配「数字 + 时间单位」这个紧邻结构，不匹配裸数字 —— 否则
#: 「酒店标准 600 元，稍等我再查下班次」里的 600 会被误伤（它确实是
#: 带回来的数据，那句不该被拦）。单位表只收**时间**单位，不收「元 / 晚 / 张」。
#:
#: ⚠️ 中文单位不写 ``\b``：``\b`` 在中文两侧的行为依赖 ``\w`` 是否包含汉字
#: （Python 里包含），写了反而匹配不上。
_TIME_ESTIMATE_PATTERN: Final[re.Pattern[str]] = re.compile(
    r"\d+\s*(?:秒钟|秒|分钟|分|小时|个?小时|min|mins|minute|minutes|sec|secs|second|seconds|hours|hour)",
    re.IGNORECASE,
)


def _has_result_data(text: str) -> bool:
    """判断文本里有没有**带回来的数据**（排掉时间估计后的数字）。

    Args:
        text (`str`): 待检查的文本。

    Returns:
        `bool`: 去掉时间估计后仍含阿拉伯数字时返回 ``True``。

    ⚠️ 凡是「有数字 ⇒ 结果已经带回来了」的保险丝，都该用这个而不是
    :func:`_has_quantity`。两者的差别就是「稍等，预计 2 分钟后给你结果」：
    前者判 True（于是放行一句空话），后者判 False（正确拦下）。
    """
    return _has_quantity(_TIME_ESTIMATE_PATTERN.sub("", text))

#: 「用第三人称盘算用户」的判据 —— 段中出现即命中。
#:
#: 比 :data:`_META_COMMENTARY_MARKERS` 更细一层：答复是**对着用户**说的，
#: 正常行文用「你」；一旦出现「他既然要去北京，可以接着帮他落地方案」这种
#: **把用户当第三方来盘算下一步**的句子，那就是写给自己的。
#:
#: ⚠️ 这条是补漏补出来的：实测 B[3] 那一轮剥掉 6 段之后，**第 7 段**
#: （「顺便把话题引向出差要素——他既然要去北京，可以接着帮他落地方案。」）
#: 因为既不以独白词开头、也没有过程性措辞而**漏网**，于是用户看到的正文
#: 以一句内心戏开头。加这条之后它才被剥掉。
#:
#: ⚠️ 之所以敢用正则配「计划性动词」而不是直接匹配「他」，是因为光有第三人称
#: 不够 —— 「他的订单还没提交」是正经答复。必须「第三人称 + 下一步打算」
#: 同时出现才算草稿。
_THIRD_PERSON_PLANNERS: Final[re.Pattern[str]] = re.compile(
    # ⚠️ 2026-10-04 收窄：原来还含 ``|已经|是`` 两个动词，但它们不是
    # 「下一步打算」——「该用户的申请**已经**提交」「他**是**本次出差的
    # 负责人」都是正经的状态陈述，被判据当成草稿之后，整段会在段首剥离
    # 里被删。docstring 里那句「必须『第三人称 + 下一步打算』同时出现」
    # 才是这条判据的本意，动词表漏掉这层语义是**实现与自述不符**。
    # 收窄后 ``他既然要去北京``（实测漏网的那段）仍被抓着。
    r"(他|她|该用户)(既然|可能|会|要|可以|应该|需要|这里|想)",
)

#: 占位符话术 —— 模型用来「结束回合但没给答案」的空话。
#:
#: ⚠️ 与 :mod:`scripts.concurrency_test` 的 ``_WAITING_PHRASES`` **故意保持
#: 同源**：那边是测试判据，这边是运行时闸门，两边的判据必须一致，否则会出现
#: 「测试说红线、线上放行」的错位。新增词时**两处都要改** ——
#: 这条「两处都要改」原来是**只写在注释里的约定**，2026-10-03 的对抗审计
#: 指出它没有任何东西守着；现在由
#: ``tests/test_orchestration_reply_guard.py`` 的
#: ``test_waiting_phrases_are_shared_with_the_concurrency_script`` 逐字比对。
#:
#: ⚠️ 这张表是**已知形状表**，不是通用判据 —— 它只能抓住见过的写法。
#: 但「见过的写法」这份名单**必须够宽**，否则拦不住真正的缺陷：早先只有
#: 六个词且「请稍候」要求四字紧邻，于是下面这些**全部原样发给用户**
#: （2026-10-03 逐条实测）::
#:
#:     请您稍候。                ← 中间多了个「您」，「请稍候」不再是子串
#:     正在为您查询，马上回来。    ← 「正在查询」不再是子串
#:     正在处理中。
#:     让我查一下，马上回来。
#:     One moment please, checking.
#:
#: 所以改成按**语义族**分组收录：等待、进行时、安抚、英文。每一族都记了
