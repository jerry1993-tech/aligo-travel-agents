def _strip_markdown_prefix(paragraph: str) -> str:
    """去掉段首的 markdown 记号，便于匹配段首规则。

    Args:
        paragraph (`str`): 原始段落文本。

    Returns:
        `str`: 去掉行首 ``#``、``*``、``-``、``>``、空格与加粗记号后的文本。
    """
    return paragraph.lstrip("#*>-\t ").lstrip("*").strip()


def _is_draft(paragraph: str, *, at_tail: bool = False) -> bool:
    """判断一个段落是不是「写给模型自己看的」。

    Args:
        paragraph (`str`): 段落原文。
        at_tail (`bool`, optional): 这一段是正文的**最后一段**吗？默认
            ``False``。⚠️ 这个开关只影响第 1 条判据取哪一档表，理由见下。

    Returns:
        `bool`: ``True`` 表示是草稿（独白 / 过程叙述 / 内部实现泄露）。

    ⚠️ 判据是五段式的：

        1. 段首像独白（:data:`_MONOLOGUE_OPENERS`）→ 是草稿；
        2. 段首在宣布一个即将执行、但没执行的动作
           （:data:`_ANNOUNCED_ACTION_OPENERS`，另加「段内无数字」保险丝）
           → 是草稿；
        3. 段中出现「我在讲自己的打算」的措辞（:data:`_META_COMMENTARY_MARKERS`）
           → 是草稿；
        4. 段中用第三人称盘算用户下一步（:data:`_THIRD_PERSON_PLANNERS`）
           → 是草稿；
        5. 段中出现内部实现名字（:data:`INTERNAL_IDENTIFIERS`）→ 是草稿。

    **没有**用「不含数字」当**通用**判据。早先的设计里有这一条（想用它把
    「陈述过程」和「陈述事实」分开），但实测证明它抓不住主要缺陷：B[6] 的
    第二段「现在我看清楚了标准：酒店单晚不超过600元…我应该直接给出这个
    结论」既有数字又是独白。改用「过程性措辞」做主判据后这个 case 才被抓到。
    它只在第 2 条里当**保险丝**用 —— 那里「有数字」恰恰等价于「动作真的
    做了、结果带回来了」，与 B[6] 的情形不同（那句里的数字是标准值，
    不是它自己查回来的）。

    ⚠️ **分档（``at_tail``）**：第 1 条判据分强/弱两档，差别**只在代价**：

        · 段首剥离（``at_tail=False``）用全表。误伤是**可逆**的 ——
          剥完若 ``_answer_problem`` 判它不可用会触发重说；而且单段文本
          在段首循环里根本不剥（``index == len(paragraphs) - 1`` 就 break）。
        · 结尾剥离（``at_tail=True``）**只认强档**。正文一旦发出，
          ``_should_retry`` 的第一条（``state.emitted``）就把它挡在重说之外：
          删掉的段落用户**永远看不到**，刷新也一样。实测缺陷（2026-10-04，
          对抗验证复现）：正文 = 「查询完成。\\n\\n根据上述差标，您可以报销的
          酒店房费上限是每晚 600 元。」—— 旧的全表把结论段判成草稿，
          结尾循环删掉它，用户只看到「查询完成。」，而剩下的内容能过
          ``_answer_problem``，所以连重说都没有。删掉的是**答案本身**，
          与「宁可留一段草稿，不可删一段答案」直接相反。

        ⚠️ 两档都写在数据上（:data:`_MONOLOGUE_OPENERS_STRONG` /
        ``_WEAK``），新加一条时**必须**选一档：进强档等于承诺
        「这句话在给用户的答复里不会出现」。
    """
    head = _strip_markdown_prefix(paragraph)
    if not head:
        return True
    openers = _MONOLOGUE_OPENERS_STRONG if at_tail else _MONOLOGUE_OPENERS
    if any(opener.match(head) for opener in openers):
        return True
    if _announces_an_unfinished_action(head, paragraph):
        return True
    if any(marker in paragraph for marker in _META_COMMENTARY_MARKERS):
        return True
    if _THIRD_PERSON_PLANNERS.search(paragraph):
        return True
    return any(name in paragraph for name in INTERNAL_IDENTIFIERS)


def _announces_an_unfinished_action(head: str, paragraph: str) -> bool:
    """判断一段话是不是「宣布了一个还没做完的动作」。

    Args:
        head (`str`): 去掉 markdown 记号后的段首（``_is_draft`` 已经算过）。
        paragraph (`str`): 段落原文。

    Returns:
        `bool`: 是「宣布动作」时返回 ``True``。

    ⚠️ 三道条件缺一不可，每一道都对应一条实测过的误判：

        1. **段首**命中 :data:`_ANNOUNCED_ACTION_OPENERS`；
        2. 动作用的是**未完成体**（后面不紧跟 了/过）——
           否则「我先确认了订单和发票信息，都齐全。」这种完整答复
           会被整段判成草稿并触发重说；
        3. **首个句子**里没有任何数据 —— 有数据说明结果已经带回来了。

    ⚠️ 第 3 条早先扫的是**整段**，实测被一句无关内容解除：
    ``"我先查一下差标。\\n你的航班 CA1234 已出票。"`` —— 段内的 ``CA1234``
    来自另一句，却把保险丝整个解除了，于是段首那句空话原样留给用户。
    改成只看首句之后，保险丝问的才是它本来想问的那件事：
    「宣布的这个动作，在这一句里带回结果了吗？」

    ⚠️ 用 :func:`_has_result_data` 而不是 :func:`_has_quantity`：
    「我先查一下，预计 2 分钟后给你结果。」也是在宣布动作，
    而时间估计里的数字不是结果。

    ⚠️ 残留风险（代理判据的代价，如实记下）：一段**没有数字、又以
    「我先查…」开头、且用未完成体**的正经答复仍会被误判。取舍理由与
    :data:`_ANNOUNCED_ACTION_OPENERS` 的说明一致 —— 漏出去的是 C 类缺陷
    （用户以为它在查，然后没有然后），误判的代价只是一次重说。
    """
    match = _ANNOUNCED_ACTION_OPENERS.match(head)
    if match is None:
        return False
    if head[match.end() :].startswith(_COMPLETED_ACTION_SUFFIXES):
        return False
    return not _has_result_data(_first_sentence(paragraph))


#: 句子的分界 —— 匹配的是**句末标记**，句子本身由切片得到。
#:
#: ⚠️ 这里踩过一个坑，记下来免得下一版又踩：第一版写成
#: ``re.split(r"([。！？!?]+\s*)", paragraph)``（带捕获组以便保留分隔符），
#: 得到的片段是 ``["我先查一下差标", "。"]`` —— **标点被切成了独立片段**。
#: 于是「剥掉开头连续的草稿句」只剥掉前半截、把那个 ``。`` 留在原地，
#: 用户看到的正文以一个孤零零的句号开头。
#: 改用 :func:`re.finditer` + 按位置切片之后，每个片段都是
#: **「内容 + 它的句末标记」**，怎么拼都还原得回原文。
#:
#: ⚠️ 三个分支分别对应三种真实写法：
#:
#:     ``[。！？!?]+\\s*``   中文句末标点（含连续标点「？！」）
#:     ``(?<=[.])\\s+``    英文句号 **加空白** —— 必须有空白，
#:                         否则「1.5」「3.14」「v1.2」会被从中间切开
#:     ``\\n+``             段内换行（模型常把并列项一行一条）
#:
#: ⚠️ 刻意**不**收更多分隔符（``；``「，」不切）：切得越碎，
#: 「剥掉开头若干句」越容易剥到正文中间去。
_SENTENCE_BOUNDARY: Final[re.Pattern[str]] = re.compile(
    r"[。！？!?]+\s*|(?<=[.])\s+|\n+",
)


def _split_sentences(paragraph: str) -> list[str]:
    """把一段话切成句子（片段**自带**句末标记，拼接可还原原文）。

    Args:
        paragraph (`str`): 段落原文。

    Returns:
        `list[str]`: 句子片段列表；空段落返回空列表。
    """
    pieces: list[str] = []
    start = 0
    for match in _SENTENCE_BOUNDARY.finditer(paragraph):
        end = match.end()
        if end > start:
            pieces.append(paragraph[start:end])
            start = end
    if start < len(paragraph):
        pieces.append(paragraph[start:])
    return pieces


def _first_sentence(paragraph: str) -> str:
    """取一段话的第一个句子（用于「这一段带回结果了吗」这类局部判断）。

    Args:
        paragraph (`str`): 段落原文。

    Returns:
        `str`: 首个句子；切不出时返回整段。
    """
    pieces = _split_sentences(paragraph)
    return pieces[0] if pieces else paragraph


def _strip_leading_draft_sentences(paragraph: str) -> str:
    """剥掉一段话**开头连续的草稿句**，保留后面的正文。

    Args:
        paragraph (`str`): 段落原文。

    Returns:
        `str`: 剥掉开头草稿句后的正文；**整段都是草稿**或**一句都没剥掉**
        时返回空串（调用方据此判断「这一段救不回来」）。

    ⚠️ 这个函数是 ``_strip_drafts`` 的**救回分支**：段落粒度的剥离会把
    「草稿句 + 真答案」同段的情况整段删掉，实测丢过答案::

        "I'll wait for the policy agent's report. 住宿标准：单晚不超过 600 元。"

    —— 这是**一句话**按空行切段的结果，整段被判草稿，于是用户只看到后面
    那段「凭发票报销。」，真正的答案静默消失，而且因为剩下的段落能过
    :func:`_answer_problem`，**连重说都不会触发**。这是本模块最不能接受的
    失败形态（静默丢答案），所以宁可多一个函数专门救它。

    ⚠️ 返回空串的两种情形必须**都**返回空串，不能返回整段：
    否则调用方会把「没剥掉任何东西」误当成「剥掉了一段」，计数虚高。
    """
    sentences = _split_sentences(paragraph)
    cut = 0
    while cut < len(sentences) and _is_draft(sentences[cut]):
        cut += 1
    if cut == 0 or cut == len(sentences):
        return ""
    return "".join(sentences[cut:]).strip()


def _strip_trailing_draft_sentences(paragraph: str) -> str:
    """剥掉一段话**结尾连续的草稿句**，保留前面的正文。

    Args:
        paragraph (`str`): 段落原文。

    Returns:
        `str`: 保留的正文；**整段都是草稿**或**一句都没剥掉**时返回空串
        （与 :func:`_strip_leading_draft_sentences` 同一套返回约定）。

    ⚠️ 这是 2026-10-04 补的**第二层救回**，起因是一个实测形状：

        「您的订单已确认，出票时间是 10 月 12 日。我应该把行程发给您。」

    整段被判草稿（段中 ``我应该`` 命中 :data:`_META_COMMENTARY_MARKERS`），
    而 :func:`_strip_leading_draft_sentences` 只剥**开头**连续的草稿句 ——
    第一句就是真答案（``cut == 0``），于是它返回空串，调用方把**整段**
    删掉，用户拿到的正文里连「订单已确认」都没有了。这正是本模块
    最不能接受的失败形态：静默丢答案。

    ⚠️ 只在**调用方本来就要删掉这一段**时才用（见 :func:`_strip_drafts`
    的段首循环）。所以它的每一处「返回正文」都是净收益：不删整段了；
    返回空串时调用方的行为与从前一字不差（照旧删）。它**不会**让任何
    原本保留的段落变短。
    """
    sentences = _split_sentences(paragraph)
    cut = len(sentences)
    while cut > 0 and _is_draft(sentences[cut - 1]):
        cut -= 1
    if cut == len(sentences) or cut == 0:
        return ""
    return "".join(sentences[:cut]).strip()


def _split_paragraphs(text: str) -> list[str]:
    """按空行切段，保留段内换行（表格、列表不能被拆散）。

    Args:
        text (`str`): 回复正文。

    Returns:
        `list[str]`: 段落列表；全空白时返回空列表。
    """
    blocks = re.split(r"\n\s*\n", text)
    return [block for block in (b.strip() for b in blocks) if block]


def _strip_drafts(text: str) -> tuple[str, int]:
    """剥离**开头与结尾**的草稿段。

    Args:
        text (`str`): 回复正文（可能是模型原样输出的一坨）。

    Returns:
        `tuple[str, int]`: ``(剥离后的正文, 被剥掉的段数)``。

    ⚠️ 安全底线：**永远不会让用户对着空白**。这条底线原来写成
    ``index < len(paragraphs) - 1``（「最后一段永不剥」），但那是个更粗的
    近似 —— 它会连带放弃「最后一段里草稿句 + 真答案同段」的救回。
    现在写成「剥到某一段发现剥完什么都不剩、且它已是最后一段，就停手」，
    底线**没有放松**（仍然留下整段），但多救回了下面这些形状：

        · 单段文本「我先查一下差标。\\n你的航班 CA1234 已出票。」
          （段内一个换行不构成段落边界，整条就是一个「段落」）
        · 末段是「草稿句 + 真答案」的拼接

    ⚠️ 段内还有一层**救回**（:func:`_strip_leading_draft_sentences`）：
    段落粒度的剥离会把「草稿句 + 真答案」同段的段落整段删掉，**静默丢答案**
    且不触发重说 —— 这是本模块最不能接受的失败形态。救回只在真剥下了
    东西（剩下的部分非空）时才生效。

    ⚠️ **结尾的草稿段**是 2026-10-04 补上的（对抗审计的 C3）。补之前只剥
    开头，于是下面这种形状里的一句独白会**原样发给用户**：

        您的航班 CA1234 已出票，10 月 12 日 08:00 起飞。

        我先调用 check_travel_policy 核对一下。

    而且这类残留**不会触发重说**（正文已经发出去了），用户看到的就是
    一个句号后面挂着模型的自言自语，刷新页面还在。

    ⚠️ 结尾剥离的边界与开头**刻意不同**：开头剥离允许把整条剥空到
    「只剩最后一段」（那段即使还是草稿也留着，靠 :func:`_answer_problem`
    触发重说）；结尾剥离则**必须至少留下一段**（``end - 1 > index``）——
    它没有重说兜底（正文已发），把结尾剥空等于把答复删掉。
    两者的共同底线是同一条：绝不让用户对着空白。

    ⚠️ 结尾剥离还**只认强档判据**（``_is_draft(..., at_tail=True)``）。
    同样是「没有重说兜底」这条理由：把一段**结论句**误判成草稿并删掉，
    用户看到的就是一份缺了答案的正文，而且屏幕上、库里都再也补不回来。
    分档的实测依据见 :func:`_is_draft` 的「分档」一节。

    ⚠️ **段首区的救回有两层**（2026-10-04 补了第二层）：
    :func:`_strip_leading_draft_sentences` 管「草稿句在前、真答案在后」，
    :func:`_strip_trailing_draft_sentences` 管反过来的形状
    （「您的订单已确认，出票时间是 10 月 12 日。我应该把行程发给您。」——
    第一句就是答案，段中一句独白把整段拖成草稿）。少了第二层，那段会被
    整段删掉，用户的答案静默消失。

    ⚠️ 只剥 ``_is_draft`` 认得的段落，**不碰正文中间**的段落：
    第一段真答案之后夹进来的独白改变的是行文结构，删它比留它风险大，
    由 :func:`_classify_suspicious_paragraphs` 计数上报。
    ⚠️ 但「段首区」**不止第一段**：救回一段之后（``continue``），
    紧跟其后的纯草稿段仍在段首区内、照旧会删 —— 那是内容前后的残渣，
    不是「正文中间」。
    """
    paragraphs = _split_paragraphs(text)
    if not paragraphs:
        return "", 0

    index = 0
    removed = 0
    while index < len(paragraphs) and _is_draft(paragraphs[index]):
        salvaged = _strip_leading_draft_sentences(paragraphs[index])
        if not salvaged:
            # ⚠️ 第二层救回：开头没有草稿句，但**结尾**有（实测形状
            # 「您的订单已确认，出票时间是 10 月 12 日。我应该把行程发给您。」
            # —— 第一句就是答案，段中一句独白把整段拖成草稿）。
            # 没有这一层时调用方会把整段删掉，静默丢答案。
            salvaged = _strip_trailing_draft_sentences(paragraphs[index])
        if salvaged:
            # 这一段里既有真内容又有草稿 —— 就地保留，继续往下看。
            # ⚠️ 这一段虽然留下来了，也必须计入 ``removed``：它**确实被改过**，
            # 而调用方拿 ``removed == 0`` 判断「能不能复用原事件」——
            # 记成 0 会把剥掉的草稿连同原事件一起发出去（这个坑很隐蔽：
            # 剥离开头那句的同时，把整段原文的事件放行了）。
            paragraphs[index] = salvaged
            removed += 1
            index += 1
            # ⚠️ 这里是 ``continue`` 而不是 ``break``（2026-10-04 改）：
            # 救回一段之后**后面紧跟着的纯草稿段仍要删**。写成 ``break``
            # 的版本在对抗验证里被击穿过 ——
            # 「你的答案。\n\n我先调用 check_travel_policy 核对一下。\n\n答案二。」
            # 会保留中间那段，把内部工具名原样端给用户（基线本来会删掉它）。
            continue
        if index == len(paragraphs) - 1:
            break  # 整段都是草稿，而它已是最后一段 —— 留草稿也比留空白强
        # ⚠️ 就地删除而不是 ``index += 1``：救回的段落在列表里**没有被删**，
        # 用下标「划线」的话，删除会跨过被保留的段落，结果里就少了东西。
        del paragraphs[index]
        removed += 1

    # ── 结尾的草稿段（见 docstring 里的 C3）──
    # ⚠️ 条件是 ``end - 1 > index`` 而不是 ``end > index``：前者保证
    # ``paragraphs[index]``（段首循环留下的那一段）**永远留在结果里**。
    # ⚠️ ``at_tail=True``：结尾剥离只认强档判据 —— 这一处删错了**不可逆**。
    end = len(paragraphs)
    while end - 1 > index and _is_draft(paragraphs[end - 1], at_tail=True):
        end -= 1
        removed += 1

    if removed == 0:
        return text, 0
    return "\n\n".join(paragraphs[:end]), removed


#: 可疑段落的**类别**取值（只用于上报，不改变行为）。
#:
#: ⚠️ 分成两类不是为了更严，是为了让「要不要做中间清洗」这件事**有依据**：
#: 两类各自的修法完全不同 —— ``internal`` 是用户可见的内部泄露（该做名字
#: 清洗），``monologue`` 是行文夹带（该压提示词）。混在一条曲线上时，
#: 一个下降会被另一个上升抵消，看不出该修哪个。
_SUSPICIOUS_INTERNAL: Final[str] = "internal"
_SUSPICIOUS_MONOLOGUE: Final[str] = "monologue"


def _classify_suspicious_paragraph(paragraph: str) -> str | None:
    """判断一段话属于哪类可疑内容（``None`` 表示不可疑）。

    Args:
        paragraph (`str`): 段落原文。

    Returns:
        `str | None`: ``"internal"``（含内部实现名）或 ``"monologue"``
        （独白 / 过程叙述 / 第三人称盘算）；不可疑时 ``None``。

    ⚠️ 与 :func:`_is_draft` 的关系**必须**是「返回 ``None`` ⟺ ``_is_draft``
    为假」—— 分类只让指标能分开看，**不是**第二套判据。这条等价性由
    ``test_classification_agrees_with_the_draft_predicate`` 逐条钉住。

    ⚠️ 顺序有意：**先查内部名**。一段话同时含工具名与「我应该」时记成
    ``internal`` —— 工具名是实打实的内部泄露，比独白更值得先修。
    """
    if any(name in paragraph for name in INTERNAL_IDENTIFIERS):
        return _SUSPICIOUS_INTERNAL
    if _is_draft(paragraph):
        return _SUSPICIOUS_MONOLOGUE
    return None


def _classify_suspicious_paragraphs(text: str) -> dict[str, int]:
    """统计各类可疑段落各有多少（只用于上报，不影响行为）。

    Args:
        text (`str`): 已剥离过的正文。

    Returns:
        `dict[str, int]`: 类别 → 段数；没有可疑段落时是空字典。
    """
    counts: dict[str, int] = {}
    for paragraph in _split_paragraphs(text):
        kind = _classify_suspicious_paragraph(paragraph)
        if kind is None:
            continue
        counts[kind] = counts.get(kind, 0) + 1
    return counts


def _count_suspicious_paragraphs(text: str) -> int:
    """统计**没被剥掉**的可疑段落总数（只用于上报，不影响行为）。

    Args:
        text (`str`): 已剥离过的正文。

    Returns:
        `int`: :func:`_classify_suspicious_paragraphs` 各类计数之和。

    存在的意义是把「本模块解决不了的那部分」变成**可观测的数字**：
    如果这个数长期不为 0，说明该做「段落中间清洗」的下一版了。

    ⚠️ 写成「分类计数求和」而不是自己遍历一遍：两份遍历会各自演化，
    出现「总数与分类对不上」的曲线（用户看到总数 3、分类加起来 2）。
    """
    return sum(_classify_suspicious_paragraphs(text).values())


#: 标点与空白 —— 判「占位话术之外还剩多少字」时先剔掉它们。
_NON_CONTENT_CHARS: Final[re.Pattern[str]] = re.compile(
    r"[\s，。、；：！？~～…—\-.,;:!?()（）\[\]【】\"'“”‘’]+",
)

#: 占位回复里，「等待话术之外」最多还能剩下几个字。
#:
#: ⚠️ 这是个**魔数**，所以把它的边界案例和各自的实测字数记在这里，
#: 改动时对着它们算，别凭感觉调：
#:
#:     真·占位  「稍等，预计 2 分钟后给你结果。」 → 剩「预计2分钟后给你结果」10 字
#:     假·占位  「您的航班稍后起飞，请稍候到登机口」 → 剩「您的航班稍后起飞到登机口」13 字
#:
#: 阈值 10 正好把这两条分开，余量 3 字 —— **余量不大，这是明知故犯的取舍**：
#: 再放宽（比如 12）会把「稍等，预计 2 小时后给你结果」这类开始漏出去，
#: 再收紧（比如 8）会开始误伤「请稍候登机」这种带实质信息的短句。
#:
#: ⚠️ **光靠字数是不够的**，反例是另一条实测缺陷：
#: ``已让政策问答智能体检索制度原文，稍等。`` 的剩余是 16 字，
#: 比上面那条假阳性（13 字）**还长** —— 任何阈值都分不开它们。
#: 所以判据是「剩余短 **或** 剩余交代了一次转交」（见 :func:`_is_placeholder`）。
#:
#: ⚠️ 为什么需要这道判据：「命中等待词 + 没有数字」两条就够的话，
#: 「您的航班稍后起飞，请稍候到登机口」这种**正经答复**会被判成占位 ——
#: 代价是触发重说，重试用尽时用户拿到的是兜底道歉而不是答案。
#: 它和「一句空话被放行」是一对反向的代价，本模块的取态一贯是
#: **宁可放过空话，也不改坏真答案**，所以这道判据是往「放过」的方向调的。
_PLACEHOLDER_MAX_RESIDUE: Final[int] = 10

#: 「助手把活转交给了别人」的措辞。
#:
#: ⚠️ 这张表是 :func:`_is_placeholder` 第三道判据的核心，也是它与
#: ``scripts/concurrency_test._DELEGATION_MARKERS`` **逐字同源**的那一份
#: （由 ``tests/test_orchestration_reply_guard.py`` 的跨实现一致性用例守着）。
#: 改一边不改另一边，会让「脚本判绿、线上拦下」——两边说的不是同一件事。
#:
#: ⚠️ 为什么用词表而不是复用 :func:`_is_draft`：这一条要判的是**残留文本
#: 本身**有没有交代转交，而 ``_is_draft`` 是一整套「像不像内心独白」的
#: 正则engine —— 它顺带命中只是因为 :data:`_META_COMMENTARY_MARKERS` 里
#: 恰好有「让政策问答」这一条。而那句「已经交给政策问答智能体了，请稍候。」
#: 就绕过去了：残留是「已经交给政策问答智能体了请」14 字，
#: 既不短、也不命中任何独白标记，于是**线上与脚本同时漏判**（2026-10-04 实测）。
#: 换句话说：靠「草稿形状」兜这一条是**碰巧**，不是设计。
#:
#: ⚠️ 全部取**多字词**，绝不收单字「让」「交」：单字会在
#: 「这笔费用交给财务报销」「让他先等等」这类正经答复里误命中。
#: 词表只收「助手是施动者、且活已经交出去了」的完整说法。
_DELEGATION_MARKERS: Final[tuple[str, ...]] = (
    "已让",
    "已经让",
    "已交给",
    "已经交给",
    "交由",
    "转交",
    "转给",
    "已安排",
    "已经安排",
    "已委托",
    "已请求",
    "已通知",
    # 「让<某个子智能体>…」的写法：上面几个前缀都盖不住没有「已」的形态。
    # ⚠️ 这几个是**子智能体的中文名**，与 :data:`_META_COMMENTARY_MARKERS`
    # 里那两条同源。新增子智能体时这里要跟着加 —— 不加的后果是
    # 「让航班助手去查查」这类占位漏判。
    "让政策问答",
    "让订单",
    "让行程",
    "让意图",
)


def _announces_delegation(residue: str) -> bool:
    """残留文本是不是在交代「我已经把这活交给别人了」。

    Args:
        residue (`str`): :func:`_placeholder_residue` 的产出（已小写去标点）。

    Returns:
        `bool`: ``True`` 表示这是一次转交交代，而不是给用户的内容。

    ⚠️ 入参**必须**是残留而不是原文：原文里的「已让」可能出现在一句正经
    答复的从句里（「已让同事帮你确认过了，票价 1850 元」——它有数字，
    第一道保险丝就该把它放行）。只在「剔掉等待话术之后剩下的全是转交交代」
    时才成立，这个顺序不能颠倒。
    """
    return any(marker in residue for marker in _DELEGATION_MARKERS)


def _placeholder_residue(text: str) -> str:
    """取「剔掉等待话术与标点之后剩下什么」。

    Args:
        text (`str`): 待判定的正文。

    Returns:
        `str`: 剩余内容（已小写、已去标点空白）。

    ⚠️ 先小写再匹配英文词条 —— :data:`WAITING_PHRASES` 里所有词条都是小写，
    而模型输出的 `One moment please` 首字母是大写的。
    """
    residue = text.lower()
    for phrase in WAITING_PHRASES:
        residue = residue.replace(phrase, "")
    return _NON_CONTENT_CHARS.sub("", residue)


def _is_placeholder(text: str) -> bool:
    """判断正文是不是「占位符式答复」。

    Args:
        text (`str`): 待判定的正文。

    Returns:
        `bool`: ``True`` 表示这是一句「让用户等」的空话，而不是答案。

    ⚠️ 判据与 ``scripts.concurrency_test.check_replies_are_answers`` 一致：
    **命中等待词 + 全文没有任何数字**。加「没有数字」这个与条件，是为了
    放过「酒店标准 600 元，稍等我再查下班次」这种**有实质内容**的回复 ——
    它对用户是有用的，不该被拦。判据不一致会让测试和线上各说各话。

    ⚠️ 「没有数字」这一半走 :func:`_has_result_data`，也就是**先抠掉时间
    估计**再判。理由见 :data:`_TIME_ESTIMATE_PATTERN`：「稍等，预计 2 分钟
    后给你结果。」含数字，用裸数字判会当场放行一句纯空话。

    ⚠️ 英文形态要**大小写无关**地比：``One moment please`` 与
    ``one moment please`` 都是同一句空话。中文没有大小写，所以只有英文
    词条受影响 —— 但 ``WAITING_PHRASES`` 是同一张表，统一小写比较即可。

    ⚠️ 还有第三道：剔掉等待话术与标点后，剩下的是**短的**、**草稿形状的**、
    或者**在交代一次转交**。加它的原因是一个实测的假阳性：
    「您的航班稍后起飞，请稍候到登机口」——一句**正经答复**，因为含
    「请稍候」且没有数字，会被前两道判据判成占位。

    ⚠️ 三个分支缺一不可：只有「短」会漏掉
    「已让政策问答智能体检索制度原文，稍等。」（剩下 16 字，是实测过的
    C 类缺陷）；只有「草稿形状」会漏掉「请您稍候。」（剩下 2 字，
    但「请您」不成形状）；只有「转交交代」会漏掉
    「稍等，预计 2 分钟后给你结果。」（没有任何转交）。细节与实测字数见
    :data:`_PLACEHOLDER_MAX_RESIDUE`。
    """
    stripped = text.strip()
    if not stripped:
        return True
    lowered = stripped.lower()
    if not any(phrase in lowered for phrase in WAITING_PHRASES):
        return False
    if _has_result_data(stripped):
        return False
    residue = _placeholder_residue(stripped)
    return (
        len(residue) <= _PLACEHOLDER_MAX_RESIDUE
        or _is_draft(residue)
        or _announces_delegation(residue)
    )


def _answer_problem(text: str) -> str | None:
    """检查一段「候选答复」是否不可用。

    Args:
        text (`str`): **已剥离草稿**的正文。

    Returns:
        `str | None`: 不可用时返回原因（进日志与指标），可用时返回 ``None``。

    三种不可用：

        - ``"empty"``：剥离后什么都不剩；
        - ``"placeholder"``：只剩一句「稍等 / 正在查询」（见 :func:`_is_placeholder`）；
        - ``"monologue"``：整段都是写给自己的（所有段落都是草稿）。
    """
    stripped = text.strip()
    if not stripped:
        return "empty"
    if _is_placeholder(stripped):
        return "placeholder"
    paragraphs = _split_paragraphs(stripped)
    if paragraphs and all(_is_draft(paragraph) for paragraph in paragraphs):
        return "monologue"
    return None


#: 数字的切词与归一 —— **与动态 Prompt 的渲染侧共用同一份实现**。
#:
#: ⚠️ 实现已迁到 :mod:`src.orchestration.amounts`（无依赖的叶子模块），这里
#: 只留下划线别名。迁移的动机是缺陷 P2：抽取侧（本文件的闸门）与渲染侧
#: （``src/orchestration/context.py`` 拼给模型看的「预算上限：… 元」）各写
#: 一份「什么算数字、怎么写才算同一个数」时，两边会**悄悄分叉** —— 一边
#: 写出 ``1.2e+06``、另一边认的是 ``1200000``，模型照抄前者的正确行为反而
#: 被闸门判成编造。规则只能有一份，所以模式串与两个函数都只定义在那里。
#:
#: ⚠️ 保留下划线别名是**有意**的：本模块的测试与文档都按私有名引用它们，
#: 而「闸门用的到底是哪一份规则」必须能在 diff 里一眼看出来。
_fold_width = fold_width
