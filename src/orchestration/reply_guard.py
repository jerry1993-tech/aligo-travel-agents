#: 文本里的**完整数字串**（含千分位与小数）。
#:
#: ⚠️ 与 :data:`_AMOUNT_PATTERN` 的分工，别混用：
#:
#:     _AMOUNT_PATTERN  「答复里哪一段是金额」—— 需要「元」或 ``¥`` 做锚
