# -*- coding: utf-8 -*-
"""**数字的切词、归一与渲染** —— 一个没有依赖的叶子模块。

为什么单独一个模块：这套规则有**两个**互不相干的消费者，它们必须逐字一致：

    · :mod:`src.orchestration.reply_guard` —— 回复守卫的接地闸门要拿正文里的
      数字去和工具返回比对（切词 + 归一）；
    · :mod:`src.orchestration.context` —— 动态 Prompt 把用户要素（预算、天数、
      人数）渲染成给模型看的文字，模型照抄之后又要被闸门比对（渲染）。

两边若各写一份「什么算一个数字、怎么写才算同一个数」，分歧的症状是
**同一段正确答复时对时错**：渲染侧写出 ``1.2e+06``、闸门侧认的是 ``1200000``，
模型照抄前者就会被判成编造 —— 而这正是 2026-10-04 实测到的缺陷（缺陷代号 P2）。
所以模式串与归一化只在这里定义一次，两边都 import 这一个。

⚠️ 本模块**只做数字的形状**，不做任何判断：什么数算「编造」、
什么叫「上限措辞」，全在 :mod:`src.orchestration.reply_guard` 里。
换名字、改措辞都不会影响这里的输出。
"""

from __future__ import annotations

import re
import unicodedata
from typing import Final

__all__ = [
    "NUMBER_TOKEN_PATTERN",
    "fold_width",
    "normalize_amount",
    "numbers_in",
    "render_amount",
]

#: 文本里的**完整数字串**（含千分位与小数）。
#:
#: ⚠️ 匹配的是整段连续数字（``\d[\d,]*``），这个「贪心」正是判据的关键：
#: 比对必须按完整数字做，不能按子串做 —— 否则「用户说 5000，答复写 500」
#: 与「工具返回 2000，答复写 200」两种编造都会因为子串恰好套住而拿到依据
#: （两处都是 2026-10-03 实测的缺陷，详见 ``_numbers_in`` 的说明）。
#:
#: ⚠️ ``\d`` 在 Python 里匹配**Unicode 十进制数字**（``re`` 模块的既定行为），
#: 所以全角数字 ``６００`` 进得来 —— 归一化那一步必须跟着折全角，
#: 否则进来的数一个都对不上。
NUMBER_TOKEN_PATTERN: Final[re.Pattern[str]] = re.compile(r"\d[\d,]*(?:\.\d+)?")

#: 全角 → 半角的字符映射表（供 :func:`fold_width` 用 ``str.translate``）。
#:
#: 只有两段：
#:
#:   · ``U+FF01..U+FF5E`` —— Unicode 的「全角形式」区，与 ASCII 的
#:     ``!``..``~`` 逐个对应，减 ``0xFEE0`` 即得半角。中文输入法下
#:     打出的全角数字（``６００``）、全角逗号（``，``）、全角句点（``．``）
#:     全在这一段里；
#:   · ``U+3000``（表意空格）→ 半角空格。
#:
#: ⚠️ **绝不能**换成 ``unicodedata.normalize("NFKC", ...)`` —— 见
#: :func:`fold_width` 的 2026-10-04 记录：NFKC 折的是「兼容等价」，
#: 范围远大于「全角」，会把 ``①`` 折成 ``1`` 并与相邻数字**粘成一个
#: 模型从没写过的数**。
_WIDTH_FOLD_TABLE: Final[dict[int, str]] = {
    codepoint: chr(codepoint - 0xFEE0) for codepoint in range(0xFF01, 0xFF5F)
}
_WIDTH_FOLD_TABLE[0x3000] = " "


def fold_width(text: str) -> str:
    """把整段文本里的**全角形式**字符折成 ASCII 等价形式。

    ⚠️ 折全角必须在**抽取之前**做一次，与 :func:`normalize_amount` 里那一步
    分工不同、两个都要：

        fold_width          管**切词**（token 的边界在哪）
        normalize_amount    管**比对**（这个 token 该怎么写）

    2026-10-04 实测：只在 ``normalize_amount`` 里折全角**不够**。句子
    「酒店差标是 １，２００ 元/晚。」里，抽取器匹配 ``\\d[\\d,]*`` —— 全角
    逗号 ``，`` 不在 ``[\\d,]`` 里，于是匹配从「２００」才开始，**归一化根本
    没机会看到完整的 1200**，闸门拿一个残缺的「200」去比对，把这段（本该按
    1200 判）的答复当成编造拦下。

    ⚠️ 折的**范围**是 2026-10-04 对抗审计收紧的（缺陷代号 F3）。当时这里是
    一个整段的 ``NFKC``，而 NFKC 连「兼容等价」一起折 —— 圈号 ``①``
    （U+2460）的兼容分解就是 ``1``：

        正文       「①600元/晚是上限。」（模型在列条目，圈号是排版符号）
        NFKC 之后   「1600元/晚是上限。」
        抽出的数    1600 —— 一个**模型从来没写过**的数
        闸门判定    编造（工具返回里只有 600）
        后果        一段正确的答复被拦下重说，而且喂给模型的纠正指令里
                    点名「1600」这个不存在的数，模型只能照着重编一遍

    根因不是「折全角错了」，而是**折的范围比需求大**：切词只需要
    「全角形式 ↔ 半角」这一层一一对应，而 NFKC 会把排版符号、罗马数字、
    连字一股脑变成 ASCII，让符号与数字**粘在一起**。

    ⚠️ 顺带的一个正确性收益：本函数是**逐字符 1:1 映射**（NFKC 不是，
    例如 ``㍿`` → ``株式会社`` 会改变长度）。调用方要在折过之后的字符串上
    按 ``match.start()`` 切窗口找「上限」措辞，1:1 保证偏移不会漂。

    ⚠️ 副作用（可接受、且方向正确）：拦截上报里的**全角数字**会变成
    ASCII 写法（``５００`` 报成 ``500``）。那条字符串会进日志、指标和
    给模型的纠正指令，ASCII 比全角更好认。

    Args:
        text (`str`): 任意文本。

    Returns:
        `str`: 折过全角的文本（**与输入等长**）。
    """
    return text.translate(_WIDTH_FOLD_TABLE)


def normalize_amount(raw: str) -> str:
    """把一个数字串规范成可比较的形式（全角转半角、去千分位、去小数尾巴）。

    ``"1,200"`` / ``"1200.0"`` / ``"1200.00"`` / ``"1200"`` / ``"１，２００"``
    全部归到 ``"1200"``。

    ⚠️ 这里**只能做「同一个数的不同写法」级别的归一**，绝不能做四舍五入或
    截断 —— 「600 与 601 是不是同一个数」这种判断一旦松掉，依赖它的闸门
    就从「抓编造」退化成「什么都抓不住」。

    ⚠️ ``NFKC`` 这一步是 2026-10-04 补的，补之前实测（现场复现）：

        工具返回   {"hotel_limit_per_night": 600}
        正文       「酒店差标是 ６００ 元/晚。」（全角，中文输入法下极常见）
        normalize_amount("６００") -> "６００"   ← 与 "600" 不相等
        闸门判定   ['６００']  —— 一段**完全正确**的答复被判成编造

    根因是 :data:`NUMBER_TOKEN_PATTERN` 的 ``\\d`` 在 Python 里匹配
    **Unicode 十进制数字**，所以全角数字**进得来**；而比对面只认 ASCII
    写法，于是进来的数一个都对不上。全角逗号 ``，`` 同理会绕过
    ``replace(",", "")``。

    ⚠️ 方向要说清：这条缺陷的代价是**把正确答案改坏**（拦下 → 重说 →
    重试用尽还可能给用户一句道歉兜底），不是放走编造 —— 但它和放走编造
    是一对，都源于「同一个数的两种写法没对齐」。

    ⚠️ 这里能安全地用 ``NFKC``，是因为**输入一定是数字 token**：所有调用点
    给的都是 :data:`NUMBER_TOKEN_PATTERN` / ``_AMOUNT_PATTERN`` 的捕获组，
    以 ``\\d`` 开头，圈号 ``①`` 这类「兼容分解成数字的符号」根本进不来，
    NFKC 能折到的只有全角数字与全角逗号。**整段文本**的折全角必须走
    :func:`fold_width`（只折一一对应的全角区）—— 在整段上跑 NFKC 正是
    缺陷 F3 的成因。

    ⚠️ 边界：NFKC 之后仍非 ASCII 的数字（阿拉伯-印度数字 ٣ 等）照旧对不上。
    中文场景下不现实，记在这里备查；真要修，得在 ``isdigit`` 一族上
    做逐字符映射，代价与收益不成比例。

    Args:
        raw (`str`): 原始数字串。

    Returns:
        `str`: 归一后的数字串。
    """
    # NFKC 把全角数字/全角逗号/全角小数点折成 ASCII，其余字符不动。
    normalized = unicodedata.normalize("NFKC", raw).strip().replace(",", "")
    # ⚠️ 必须先确认有小数点再 rstrip("0")：整数串没有小数点，
    # 直接 rstrip 会把 600 变成 6 —— 那是一个**放大一百倍**的错误。
    if "." in normalized:
        normalized = normalized.rstrip("0").rstrip(".")
    return normalized


def numbers_in(text: str) -> set[str]:
    """抽出文本里出现过的**全部数字**（按 :func:`normalize_amount` 归一）。

    ⚠️ 抽出的是**完整数字串**，这正是本函数存在的理由：判断「用户说过 500
    没有」不能拿 ``"500" in "预算是 5000"`` 这种子串匹配 —— 那会把 500
    判成「用户说过」。同样的坑在工具侧也有：``check_travel_policy`` 的返回里
    同时有酒店 600 与机票 **2000**，``"200" in "2000"`` 为真，于是
    「酒店差标是 200 元」这种编造自动获得了「依据」。两处都是同一个错：
    拿子串当数字比。

    ⚠️ 先折全角再抽取（见 :func:`fold_width`）：工具返回与用户原话都可能
    带全角（中文语料灌进知识库、用户用中文输入法打字），不折的话
    ``１，２００`` 会被切出一个残缺的 ``２００``。

    Args:
        text (`str`): 任意文本。

    Returns:
        `set[str]`: 归一后的数字串集合。
    """
    return {
        normalize_amount(token)
        for token in NUMBER_TOKEN_PATTERN.findall(fold_width(text))
    }


def render_amount(value: float) -> str:
    """把金额渲染成**不改写**的十进制字符串（供 prompt 与工具返回使用）。

    ⚠️ 存在的理由是 ``f"{value:g}"``：``:g`` 只保留 **6 位有效数字**，超出
    即改写，且会切成科学计数法（2026-10-04 实测）：

        f"{15000.0:g}"    -> "15000"
        f"{1234567.0:g}"  -> "1.23457e+06"
        f"{1200000.0:g}"  -> "1.2e+06"
        f"{999999.5:g}"   -> "1e+06"
        f"{12345.678:g}"  -> "12345.7"

    这一串会被写进**给模型看的文字**（动态 Prompt 的「预算上限：… 元」、
    差旅工具返回的「酒店 … 元/晚」）。而提示词要求模型「原样引用、不凑整」，
    模型照做就会把 ``1.2e+06 元`` 这个用户没说过、也读不出来的串发给用户；
    反过来，模型若写成正常人写法的 ``1200000 元``，接地闸门又会因为工具
    返回里记的是科学计数法而判成无依据 —— **管道自己违反了它对模型提出的
    数字纪律**（缺陷代号 P2）。

    ⚠️ 整数值走 ``int`` 分支，是为了不出现 ``1200000.0`` 这种尾巴；
    非整数值保留到小数点后 6 位再削零 —— 金额的精度需求远低于此，
    而它保证「用户说多少就写多少」，不做四舍五入。

    Args:
        value (`float`): 金额。

    Returns:
        `str`: 十进制写法（不带千分位 —— 千分位是给人看的排版，
        而这里这句话的读者是模型，它要照抄；且带千分位的数字在
        工具返回里会让闸门多做一次千分位归一）。
    """
    if float(value).is_integer():
        return f"{int(value):d}"
    return f"{value:.6f}".rstrip("0").rstrip(".")
