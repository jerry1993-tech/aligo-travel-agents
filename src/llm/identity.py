# -*- coding: utf-8 -*-
"""保留身份登记处：**客户端永远不能自称**的那些 user_id。

文件职责：
    回答一个问题 —— 框架的身份就是一个字符串（``X-User-ID`` 或 JWT 的
    ``sub``），那么「谁的身份是不允许被客户端直接声明的？」，以及
    「凭据写到哪个属主名下才算系统资源？」。答案就是本模块里的一个集合。

上下游依赖：
    - 上游：**没有任何 import**（见下）。
    - 下游：
        · ``src/server/middleware/auth.py`` —— 拒绝客户端（或 token）
          断言一个保留身份；
        · ``src/llm/system_credential.py`` —— 系统凭据的属主取自这里。

==============================================================================
为什么是一个零 import 的叶子模块
==============================================================================
    ``SystemCredentialAccessPolicy`` 与系统凭据的播种逻辑住在
    ``src/llm/system_credential.py``，而那个模块在 import 期会拉进
    ``agentscope.app.access``（框架的资源访问策略基类）。

    鉴权中间件却在**每一次请求**的路径上，而且它是「零密钥启动」这条
    README 承诺的开箱即用路径上的第一道门 —— 让它在 import 期多背一个
    框架子包，只为了读一个字符串常量，是不划算的：``agentscope`` 的
    任何 import 期副作用都会变成「服务起不来」而不是「鉴权多一条规则」。

    所以常量单独放在这里，**不 import 任何东西**。任何模块在任何时刻
    import 它都拿到完整内容，不会有循环、不会有副作用。
    ⚠️ 因此不要为了「顺手」往本模块加需要 import 的东西 —— 一旦它有了
    依赖，它就不再是叶子，上面那条理由就失效了。
"""

from __future__ import annotations

#: 系统凭据的**属主**。它是一个普通 user_id，只是不来自任何真实登录 ——
#: 框架的存储层不区分「系统」与「用户」，属主只是一个隔离维度。
#:
#: ⚠️ 取一个不可能与真实登录名撞车的值（``aligo-`` 前缀 + 固定词）。
#: 若它与某个用户的 id 相同，那条凭据就成了「该用户的私有凭据」，
#: 而共享逻辑会因为它属于调用者本身而跳过 —— 症状是「只有那个用户还能用」。
SYSTEM_USER_ID = "aligo-system"

#: **保留身份**：HTTP 客户端（以及任何 token 的 ``sub``）都不得声明的 user_id。
#:
#: 为什么必须有这条规则：框架的 ``get_current_user_id`` 把请求头里的
#: 身份**当作事实**（``app/deps.py``，自述是临时方案），而凭据的可见性
#: 完全由「你是不是属主」决定 ——
#:
#:     · 属主读自己的凭据是**明文**（``app/_service/_access.py::_build_view``
#:       只对非属主打码），
#:     · 属主还拿到 ``editable: true``，可以改、可以**删**。
#:
#: 于是 ``X-User-ID: aligo-system`` 一次请求就能：读出运营者的真实 API key、
#: 或把那条全员共享的凭据删掉（所有人当场用不了模型）。
#: 这不是「提权」—— 在 ``X-User-ID`` 直连模式里身份本来就不校验；它是
#: **把内部身份当成了可声明的身份**。系统身份从来不是给客户端用的，
#: 它只是存储层的一个隔离维度。
#:
#: 判据与共享策略里的 ``viewer_id == SYSTEM_USER_ID`` 是**同一条规则的
#: 两个方向**：那一条保证「属主自己不会在共享列表里再看见一次」，
#: 这一条保证「没人能假装成那个属主」。两处必须同时成立。
RESERVED_USER_IDS: frozenset[str] = frozenset({SYSTEM_USER_ID})


def is_reserved_user_id(user_id: str) -> bool:
    """判断 ``user_id`` 是不是一个客户端不得声明的保留身份。

    ⚠️ **精确比较**（调用方先 ``strip()``），不做大小写折叠 ——
    这不是疏忽，而是因为判据必须与框架的判据**逐字节一致**：

        框架是拿请求头的值去和 ``record.user_id`` 做 ``==`` 的
        （``storage/_sql/_storage.py::get_credential``）。也就是说
        ``"ALIGO-SYSTEM"`` 或 ``"aligo-system "`` 在框架眼里本就是一个
        **不同的用户** —— 它既不是属主、读到的凭据也照样是打码的。

    所以「只拒绝逐字节相同的值」既不漏（任何能冒充属主的写法都恰好相等），
    也不误伤（不会把某个恰好形似的真实用户挡在门外）。
    把比较写成 ``casefold`` 之类的「更严格」，换来的只是
    「一个本来安全的写法被拒」这种难以解释的行为。

    Args:
        user_id (`str`): 已 ``strip()`` 的身份字符串。

    Returns:
        `bool`: 是保留身份返回 True。
    """
    return user_id in RESERVED_USER_IDS


__all__ = [
    "RESERVED_USER_IDS",
    "SYSTEM_USER_ID",
    "is_reserved_user_id",
]
